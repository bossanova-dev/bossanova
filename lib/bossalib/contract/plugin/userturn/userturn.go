// Package userturn classifies the text of a user turn in an agent transcript.
//
// A transcript's user turns are not all typed by a person. The agent's harness
// writes wrappers only the agent reads (system reminders, a slash command's
// expansion, local-command output, task notices), and bossd pastes notices
// from outside the conversation (a GitHub callback, a broadcast). A reader that
// shows every user turn as a person's message shows raw XML and machine
// prompts as if someone had said them. Classify says what each one is.
package userturn

import (
	"regexp"
	"strings"
)

// Kind is what a user turn really is.
type Kind int

const (
	// Message is a message to the agent; Turn.Text is its text, wrappers removed.
	Message Kind = iota
	// Command is a slash command or skill the turn ran; Turn.Text is "/name args".
	Command
	// Event is a notice from outside the conversation; Turn.Event says what.
	Event
	// Harness is a wrapper only the agent reads. A reader drops it.
	Harness
)

// Notice sources, as ChatEvent.source carries them.
const (
	SourceGitHub    = "github"
	SourceBossanova = "bossanova"
	SourceAgent     = "agent"
)

// Notice is an Event turn's content.
type Notice struct {
	Source string
	Text   string
	URL    string
}

// Turn is one classified user turn.
type Turn struct {
	Kind  Kind
	Text  string
	Event Notice
}

var (
	reminderRe    = regexp.MustCompile(`(?s)<system-reminder>.*?</system-reminder>`)
	pastedRe      = regexp.MustCompile(`(?s)<pasted_content\b[^>]*>(.*?)</pasted_content>`)
	commandNameRe = regexp.MustCompile(`(?s)<command-name>(.*?)</command-name>`)
	commandArgsRe = regexp.MustCompile(`(?s)<command-args>(.*?)</command-args>`)
	taskSummaryRe = regexp.MustCompile(`(?s)<summary>(.*?)</summary>`)
	openTagRe     = regexp.MustCompile(`^<([a-zA-Z][\w-]*)[\s>]`)
	codexSkillRe  = regexp.MustCompile(`^\$[a-z][a-z0-9:_-]*(?:\s|$)`)
	// callbackRe is the head bossd's callback.BuildCallbackPrompt writes: the
	// trigger, its verified state, the pull request, the callback id and an
	// optional group, then the pull request's URL and the signal-only warning.
	callbackRe = regexp.MustCompile(`^GitHub callback: ([a-z_]+) \(verified[^)\n]*\) · ([\w.-]+)/([\w.-]+)#(\d+) · id \S+(?: · group \S+)?\n(https://github\.com/\S+)\n\nSignal only — re-verify PR and session state before acting\.`)
)

// The frames bossd writes around a callback's and a broadcast's message body
// (services/bossd/internal/callback and services/bossd/internal/broadcast).
// bossd marks its injected turns in no other way, so a turn counts as bossd's
// only when it carries bossd's whole frame: its head and its closing delimiter.
const (
	callbackEnd   = "----- END REGISTERED MESSAGE -----"
	broadcastHead = "Broadcast received.\n\nBroadcast ID: "
	broadcastEnd  = "----- END BROADCAST MESSAGE -----"
)

// Plain-text harness turns: Claude Code's local-command caveat, and the
// AGENTS.md document Codex pastes in its INSTRUCTIONS envelope.
const (
	localCaveat    = "Caveat: The messages below were generated by the user while running local commands."
	codexAgentsDoc = "# AGENTS.md instructions"
	codexAgentsEnd = "</INSTRUCTIONS>"
)

// harnessTags are the envelopes Claude Code and Codex write into a user turn
// for the agent alone; a turn that opens with one is Harness. The set is
// closed, so a person's own tag-wrapped text stays a Message. bossd writes no
// tagged turns of its own. System reminders, slash commands and task
// notifications are handled before this set is consulted.
var harnessTags = map[string]bool{
	// Claude Code.
	"local-command-stdout":    true,
	"local-command-stderr":    true,
	"local-command-caveat":    true,
	"bash-input":              true,
	"bash-stdout":             true,
	"bash-stderr":             true,
	"user-prompt-submit-hook": true,
	// Codex.
	"environment_context":              true,
	"user_instructions":                true,
	"user_shell_command":               true,
	"turn_aborted":                     true,
	"subagent_notification":            true,
	"agent_message_board_notification": true,
	"startup_context":                  true,
	"skill":                            true,
}

// Classify says what a user turn's raw text is.
func Classify(raw string) Turn {
	text := reminderRe.ReplaceAllString(raw, "")
	text = strings.TrimSpace(pastedRe.ReplaceAllString(text, "$1"))
	if text == "" {
		return Turn{Kind: Harness}
	}
	if name := commandNameRe.FindStringSubmatch(text); name != nil {
		return command(name[1], text)
	}
	if turn, ok := notice(text); ok {
		return turn
	}
	if harness(text) {
		return Turn{Kind: Harness}
	}
	if codexSkillRe.MatchString(text) {
		return Turn{Kind: Command, Text: text}
	}
	return Turn{Kind: Message, Text: text}
}

func command(name, text string) Turn {
	cmd := strings.TrimSpace(name)
	if !strings.HasPrefix(cmd, "/") {
		cmd = "/" + cmd
	}
	if args := commandArgsRe.FindStringSubmatch(text); args != nil {
		if a := strings.TrimSpace(args[1]); a != "" {
			cmd += " " + a
		}
	}
	return Turn{Kind: Command, Text: cmd}
}

// notice recognizes the turns bossd and the harness write about something that
// happened outside the conversation.
func notice(text string) (Turn, bool) {
	event := func(source, what, url string) (Turn, bool) {
		return Turn{Kind: Event, Event: Notice{Source: source, Text: what, URL: url}}, true
	}
	switch {
	case strings.HasPrefix(text, "<task-notification>"):
		summary := "A background task finished"
		if m := taskSummaryRe.FindStringSubmatch(text); m != nil && strings.TrimSpace(m[1]) != "" {
			summary = strings.TrimSpace(m[1])
		}
		return event(SourceAgent, summary, "")
	case strings.HasPrefix(text, "[Request interrupted by user"):
		return event(SourceAgent, "Interrupted", "")
	case strings.HasPrefix(text, broadcastHead) && strings.HasSuffix(text, broadcastEnd):
		return event(SourceBossanova, "Broadcast received", "")
	}
	if m := callbackRe.FindStringSubmatch(text); m != nil && strings.HasSuffix(text, callbackEnd) {
		owner, repo, number, url := m[2], m[3], m[4], m[5]
		if url == "https://github.com/"+owner+"/"+repo+"/pull/"+number {
			return event(SourceGitHub, strings.ReplaceAll(m[1], "_", " ")+" on "+owner+"/"+repo+"#"+number, url)
		}
	}
	return Turn{}, false
}

// harness reports whether the text is an envelope the agent's harness wrote.
func harness(text string) bool {
	if open := openTagRe.FindStringSubmatch(text); open != nil && harnessTags[open[1]] {
		return true
	}
	return strings.HasPrefix(text, localCaveat) ||
		(strings.HasPrefix(text, codexAgentsDoc) && strings.HasSuffix(text, codexAgentsEnd))
}
