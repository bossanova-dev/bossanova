test('BOS-674: every extracted step names the reference on its OWN resident line (both mirrors)', () => {
  // The extraction left five summary bullets in the resident body and ONE preamble link. A
  // whole-body search for the filename — which is all the reachability test above does — passes
  // on that single preamble occurrence, so it cannot distinguish "each step points at its
  // instructions" from "one paragraph does, and the five bullets read as self-contained steps".
  // That difference is the failure mode: an agent that works the bullets without opening the
  // reference skips the tag injection, the green gate, the deferral gate, proof, and the lock
  // release, while every assertion here stays green. Pin the pointer per step, on the step's own
  // line, in both Go mirrors.
  for (const dir of BUILD_MIRRORS) {
    const body = fs.readFileSync(path.join(rootDir, dir, 'SKILL.md'), 'utf8')
    // Slice on markers that must exist: a missing marker makes `indexOf` return -1 and a negative
    // bound would hand back a slice from elsewhere in the file that could satisfy these checks.
    const start = body.indexOf('## Steps 8-12:')
    const end = body.indexOf('## Cron gate')
    assert.ok(
      start !== -1 && end > start,
      `${dir}/SKILL.md must still carry the Steps 8-12 pointer block`,
    )
    const lines = body.slice(start, end).split('\n')
    for (const step of [8, 9, 10, 11, 12]) {
      const line = lines.find((candidate) =>
        new RegExp(String.raw`^- \*\*\[?Step ${step}\b`).test(candidate),
      )
      assert.ok(line, `${dir}/SKILL.md must keep a resident summary bullet for Step ${step}`)
      assert.ok(
        line.includes(FINALIZE_REF),
        `${dir}/SKILL.md Step ${step}'s resident line must name ${FINALIZE_REF} itself, not lean on the block's single preamble link`,
      )
    }
    // And the bullets must say what they are, so a reader who reaches one first does not take it
    // for the instruction. Without this the per-step links are navigable but not mandatory.
    assert.match(
      body.slice(start, end),
      /Each bullet is a summary, never the instruction/,
      `${dir}/SKILL.md must state the Steps 8-12 bullets are summaries, not the instructions`,
    )
  }
})

// BOS-814: the methodology extension no longer vendors an implementation loop of its own — it
// dispatches Compound Engineering's `ce-work` and holds a caller-owned boundary around it, because
// `ce-work` ships by default (its Phase 3-4 pushes, opens a PR, and flips the plan doc's status).
// Boss owns worktree lifecycle, commits, verification, and shipping, so the boundary is the whole
// safety property of routing through CE at all. Pin it in BOTH mirrors.
test('methodology extension dispatches ce-work under the caller-owned boundary in both mirrors', () => {
  for (const skillDir of METHODOLOGY_EXTENSION_DIRS) {
    const skill = fs.readFileSync(path.join(skillDir, 'SKILL.md'), 'utf8')
    const flat = skill.replace(/\s+/g, ' ')

    assert.match(skill, /role: methodology/, `${skillDir}/SKILL.md must keep role: methodology`)
    assert.match(
      skill,
      /compound-engineering:ce-work/,
      `${skillDir}/SKILL.md must name the ce-work skill it dispatches`,
    )
    assert.match(
      flat,
      /caller-owned/i,
      `${skillDir}/SKILL.md must name the caller-owned mode it runs ce-work in`,
    )
    // Boss keeps ownership of the steps ce-work would otherwise take itself.
    assert.match(
      flat,
      /Boss owns worktree lifecycle, commits, verification,?\s*and shipping/i,
      `${skillDir}/SKILL.md must state Boss owns worktree lifecycle, commits, verification, and shipping`,
    )
    // The concrete prohibitions. Without these the boundary is a slogan: ce-work's own shipping
    // workflow pushes, opens the PR, and flips the plan doc's status, and its Phase 1 offers to
    // switch/rename branches.
    //
    // Scope them to the "Stop before the shipping workflow" bullet rather than the whole flattened
    // document, and require the negative wording itself. Matching bare command names anywhere in
    // the file is polarity-blind: a bullet rewritten to ALLOW `git checkout` / `git switch` would
    // still satisfy it, leaving the Boss-owned worktree boundary ungated by a test that claims to
    // gate it.
    const stopBullet = flat.match(/\*\*Stop before the shipping workflow\.\*\*(.+?)(?=- \*\*|$)/i)
    assert.ok(
      stopBullet,
      `${skillDir}/SKILL.md must carry the "Stop before the shipping workflow" boundary bullet`,
    )
    const prohibitions = stopBullet[1]
    for (const [label, pattern] of [
      ['no push', /\bno\s+`?git push`?/i],
      ['no PR create/edit', /\bno\s+PR create/i],
      ['no branch create/switch', /\bno\s+`?git checkout`?\s*\/\s*`?git switch`?/i],
      ['no plan-doc status flip', /\bno\s+plan-doc\s+`?status`?\s+flip/i],
    ]) {
      assert.match(
        prohibitions,
        pattern,
        `${skillDir}/SKILL.md's shipping-workflow bullet must forbid ${label} — Boss owns shipping and plan state, not ce-work`,
      )
    }
    // Boss runs its own review stack at Step 6; a Tier-2 escalation from inside ce-work duplicates
    // it and can mutate the tree outside the core's ownership snapshot.
    assert.match(
      flat,
      /not escalate to `?ce-code-review`?/i,
      `${skillDir}/SKILL.md must forbid escalating to ce-code-review from inside ce-work`,
    )
    // Headless: ce-work's Phase 1 says "ask clarifying questions now"; this extension must not.
    assert.match(
      flat,
      /[Nn]ever ask clarifying questions/,
      `${skillDir}/SKILL.md must override ce-work's clarifying-question step for headless runs`,
    )
  }
})

