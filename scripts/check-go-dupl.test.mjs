import { test } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import {
  parseDuplReport,
  pairCounts,
  compareToBaseline,
  checkModule,
  main,
  readDuplPin,
} from './check-go-dupl.mjs'

const report = (groups) =>
  groups
    .map(
      (g) =>
        `found ${g.length} clones:\n${g.map((m) => `  ${m.file}:${m.start},${m.end}`).join('\n')}\n`,
    )
    .join('\n') + `\nFound total ${groups.length} clone groups.\n`
const member = (file, start = 1) => ({ file, start, end: start + 20 })
function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'go-dupl-'))
  t.after(() => fs.rmSync(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 }))
  fs.mkdirSync(path.join(root, 'services/sample'), { recursive: true })
  fs.mkdirSync(path.join(root, 'scripts'))
  fs.writeFileSync(path.join(root, 'Makefile'), 'DUPL_PKG := github.com/mibk/dupl@v1.1.0\n')
  fs.writeFileSync(path.join(root, 'services/sample/go.mod'), 'module sample\n')
  for (const file of ['a.go', 'b.go', 'z.go', 'a_test.go', 'b_test.go'])
    fs.writeFileSync(path.join(root, 'services/sample', file), 'package sample\n')
  fs.writeFileSync(
    path.join(root, 'scripts/go-dupl-baseline.json'),
    JSON.stringify({ threshold: 100, modules: { 'services/sample': {} } }),
  )
  return root
}
const run = (text) => () => ({ status: 0, stdout: text, stderr: '' })

test('new pair fails with module, measured count, baseline and regeneration remedy', (t) => {
  const repoRoot = fixture(t)
  const result = checkModule({
    repoRoot,
    moduleDir: 'services/sample',
    runDupl: run(report([[member('a.go'), member('b.go')]])),
  })
  assert.equal(result.ok, false)
  assert.match(result.lines.join('\n'), /services\/sample.*a\.go\|b\.go.*measured 1 > baselined 0/)
  assert.match(
    result.lines.join('\n'),
    /node scripts\/check-go-dupl\.mjs --module services\/sample --write-baseline/,
  )
  assert.match(result.lines.join('\n'), /a\.go:1,21/)
})

test('line shifts leave pairs unchanged and pass the baseline', () => {
  const original = pairCounts(parseDuplReport(report([[member('a.go'), member('b.go')]])).groups)
  const shifted = pairCounts(
    parseDuplReport(report([[member('a.go', 101), member('b.go', 201)]])).groups,
  )
  assert.deepEqual(original, shifted)
  assert.deepEqual(compareToBaseline(shifted, original), { newPairs: [], stalePairs: [] })
})

test('shrinking a group preserves surviving pairs and reports only removed pairs stale', () => {
  const old = pairCounts([[member('a.go'), member('b.go'), member('c.go')]])
  const current = pairCounts([[member('a.go'), member('b.go')]])
  assert.deepEqual(compareToBaseline(current, old), {
    newPairs: [],
    stalePairs: [
      { pair: 'a.go|c.go', measured: 0, baselined: 1 },
      { pair: 'b.go|c.go', measured: 0, baselined: 1 },
    ],
  })
})

test('four members produce all six unordered pairs regardless of reporter order', () => {
  const group = ['a.go', 'b.go', 'c.go', 'd.go'].map((f) => member(f))
  assert.equal(Object.keys(pairCounts([group])).length, 6)
  assert.deepEqual(pairCounts([group]), pairCounts([[...group].reverse()]))
  assert.deepEqual(pairCounts([[member('a.go'), member('a.go', 50)]]), { 'a.go|a.go': 1 })
})

test('test-test and generated members are excluded while test-production pairs count', (t) => {
  const repoRoot = fixture(t)
  fs.writeFileSync(
    path.join(repoRoot, 'services/sample/generated.go'),
    '// Code generated by sample. DO NOT EDIT.\npackage sample\n',
  )
  const result = checkModule({
    repoRoot,
    moduleDir: 'services/sample',
    runDupl: run(
      report([
        [
          member('a.go'),
          member('a_test.go'),
          member('b_test.go'),
          member('gen/proto.go'),
          member('generated.go'),
        ],
      ]),
    ),
  })
  assert.deepEqual(result.counts, { 'a.go|a_test.go': 1, 'a.go|b_test.go': 1 })
})

test('broken reports and runner failures cannot pass as zero clones', (t) => {
  const repoRoot = fixture(t)
  for (const text of [
    '',
    'unrecognised reporter',
    'Found total 1 clone groups.\n',
    'found 3 clones:\n a.go:1,20\n b.go:1,20\nFound total 1 clone groups.',
  ]) {
    const result = checkModule({ repoRoot, moduleDir: 'services/sample', runDupl: run(text) })
    assert.equal(result.ok, false, text)
    assert.match(result.lines.join('\n'), /dupl produced no parseable report/)
  }
  const result = checkModule({
    repoRoot,
    moduleDir: 'services/sample',
    runDupl: () => ({ status: 1, stdout: '', stderr: 'network transport failed' }),
  })
  assert.equal(result.ok, false)
  assert.match(result.lines.join('\n'), /network transport failed/)
  assert.equal(
    checkModule({ repoRoot, moduleDir: 'services/sample', runDupl: run(report([])) }).ok,
    true,
  )
})

test('baseline regeneration sorts keys and is byte-identical across repeated runs', (t) => {
  const repoRoot = fixture(t)
  const input = report([
    [member('z.go'), member('a.go')],
    [member('b.go'), member('a.go')],
  ])
  assert.equal(main(['--write-baseline'], { repoRoot, runDupl: run(input), log: () => {} }), 0)
  const baseline = fs.readFileSync(path.join(repoRoot, 'scripts/go-dupl-baseline.json'), 'utf8')
  assert.ok(baseline.indexOf('a.go|b.go') < baseline.indexOf('a.go|z.go'))
  assert.equal(main(['--write-baseline'], { repoRoot, runDupl: run(input), log: () => {} }), 0)
  assert.equal(
    fs.readFileSync(path.join(repoRoot, 'scripts/go-dupl-baseline.json'), 'utf8'),
    baseline,
  )
  assert.equal(main([], { repoRoot, runDupl: run(input), log: () => {} }), 0)
})

test('missing or floating dupl pin fails loudly', (t) => {
  const repoRoot = fixture(t)
  for (const text of ['', 'DUPL_PKG := github.com/mibk/dupl@latest\n']) {
    fs.writeFileSync(path.join(repoRoot, 'Makefile'), text)
    assert.throws(() => readDuplPin(repoRoot), /DUPL_PKG.*pinned/)
  }
})

test('baseline validates positive threshold and counts and allows unlisted modules', (t) => {
  const repoRoot = fixture(t)
  for (const baseline of [
    { threshold: 0, modules: {} },
    { threshold: 100, modules: { 'services/sample': { 'a.go|b.go': 0 } } },
  ]) {
    fs.writeFileSync(path.join(repoRoot, 'scripts/go-dupl-baseline.json'), JSON.stringify(baseline))
    assert.equal(
      checkModule({ repoRoot, moduleDir: 'services/sample', runDupl: run(report([])) }).ok,
      false,
    )
  }
  fs.writeFileSync(
    path.join(repoRoot, 'scripts/go-dupl-baseline.json'),
    JSON.stringify({ threshold: 100, modules: {} }),
  )
  assert.equal(
    checkModule({ repoRoot, moduleDir: 'services/sample', runDupl: run(report([])) }).ok,
    true,
  )
})
