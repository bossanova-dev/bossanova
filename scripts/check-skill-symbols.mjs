#!/usr/bin/env node

// Symbol-contract gate for skill prose (BOS-639).
//
// Skill bodies confidently name config roles, toolbox exports and helper CLI verbs.
// When one of those names is wrong — or drifts out from under the prose when the
// source is renamed — nothing discovers it but an autonomous run burning a cycle.
// This gate asserts that every MACHINE-CHECKABLE symbol citation in the two owned
// skill roots resolves against real repo state.
//
// Scope: `.claude/skills/` and `services/boss/internal/skillinstall/skills/`, all
// `*.md` (real citations live in `references/`, not only `SKILL.md`). Deliberately
// NOT scanned: `plugins/bossd-plugin-claude/skilldata/skills/` and `.codex/skills/`
// (generated byte-identical mirrors, gated by `make copy-skills` /
// `make codex-skills-check` — scanning them would double-report every finding), and
// each skill's `toolbox/` subdirectory (vendored `.mjs`, not prose).
//
// Three checks:
//   1. tracker role citations  — `labelName(config, 'agentFriendly')` and friends,
//      resolved through loadSkillConfig + adapterFor/trackerConfigFor (NOT a
//      hard-coded `linear` branch), plus the bidirectional taxonomy assertion that
//      content labels are never routed through `labelName`.
//   2. toolbox export citations — inline-code CALL citations inside the skills that own
//      a vendored `toolbox/` (discovered from the tree), resolved against the flat union of
//      `skills-toolbox/**` + `scripts/**` exports and the tracker capability/operation
//      constants.
//   3. helper CLI verbs — `node <path>.mjs <verb>`, resolved by basename union against
//      each helper's own dispatch.
//
// WHAT THIS GATE DELIBERATELY DOES NOT CHECK — and the measured cost of adding it.
// Read the numbers before "just checking everything": a gate that produces false
// positives gets disabled, and then it checks nothing at all.
//
//   * Bare (non-call) symbol citations. Widening check 2 to bare `camelCaseToken`
//     inside the 9 toolbox-owning skills yields 353 candidates of which **210 do not
//     resolve** (63 unique names — JSON fields, MCP tool names, config keys, role
//     keys: `registerWatch`, `agentFriendly`, `blockedBy`, `descriptionSummary`,
//     `openQuestions`, ...). Rejected outright. Known cost: bare citations such as
//     `assertAcyclic`, `validateLayering` and the four plan-attachment operations
//     are unchecked.
//   * A global, unscoped export rule (dropping the toolbox-owning-skill scope) leaves
//     **34** unresolved citations. Also rejected.
//   * Helper CLI verbs cited without the literal `node` token: dropping that
//     requirement takes check 3 from 88 citations / 0 false positives to 110 hits of
//     which **~15** are prose ("`bs-run-sentinel.mjs` missing (needs BOS-144)" x13,
//     "`driver.mjs` as" x2, "`plan-slug.mjs` issue").
//   * Module attribution for export citations. Only 4 of 46 call citations name a
//     `.mjs` on the same line, so attribution is undeterminable for 91% of the
//     population. This gate checks EXISTENCE, not attribution.
//   * Wrong-module verb attribution. Basename union means a verb belonging to a
//     same-basename sibling passes. That is a false negative, and it is the price of
//     resolving `cli.mjs` (tracker/ and finalize/) and `skill-extensions.mjs` (a
//     zero-dispatch re-export shim whose real dispatch lives in skills-toolbox/).
//   * Variable-indirect helper invocations (`RUN_SENTINEL="…/bs-run-sentinel.mjs"`
//     then `"$RUN_SENTINEL" write …`). This is why `bs-run-sentinel.mjs` and
//     `linear-claim.mjs` have zero `node`-form citations despite heavy use.
//   * Argument order / arity. The one real case (`validatePlanDescription` is
//     config-first) has a single BARE citation, so the rule would be vacuous — and it
//     would false-positive on `m.isConfiguredForPlanning(c)` in an inline `node -e`.
//   * Unused documented return values (`target.repo`) — a reachability question, not
//     a does-this-symbol-exist question.
//   * Cited-path existence — the sibling prose-path gate owns it.
//   * Go, SQL, shell and MCP-tool identifiers, and non-camelCase single-word exports.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { isMainModule } from '../skills-toolbox/main-module.mjs'
import { adapterFor, loadSkillConfig, trackerConfigFor } from '../skills-toolbox/skill-config.mjs'
import {
  OPTIONAL_TRACKER_CAPABILITIES,
  OPTIONAL_TRACKER_OPERATIONS,
  REQUIRED_TRACKER_OPERATIONS,
  TRACKER_CAPABILITIES,
} from '../skills-toolbox/tracker/adapter-core.mjs'

// The two roots this repo owns. The generated mirrors are excluded by omission AND
// by EXCLUDED_PATH_SEGMENTS below, so a future root addition cannot re-admit them.
export const SKILL_ROOTS = ['.claude/skills', 'services/boss/internal/skillinstall/skills']

// Where the canonical `.mjs` modules live. Both indexes read the same roots.
export const MODULE_ROOTS = ['skills-toolbox', 'scripts']

// Directory names never walked when collecting skill prose.
const EXCLUDED_DIR_NAMES = new Set(['toolbox', 'node_modules'])

// Path fragments never walked, even if a caller points a root at them.
const EXCLUDED_PATH_SEGMENTS = ['.codex/skills', 'plugins/bossd-plugin-claude/skilldata/skills']

// The 9 skills that vendor a `toolbox/` as of this writing. Inside them the symbol
// vocabulary is closed; outside them it is not, so check 2 only reads owners.
//
// This list does NOT gate check 2 — discoverToolboxOwners() reads the tree, so a skill
// that starts vendoring a toolbox is covered the moment it lands rather than whenever
// someone remembers to edit an unrelated constant. What the list gates is drift: the
// derived set is compared against it and any difference is reported. That is the
// tripwire for the other direction, where derivation quietly returns fewer owners than
// it should (a moved root, a renamed `toolbox/`, an fs shape this walker misreads) and
// check 2 degrades to asserting nothing on the skills it was written for — the same
// silent-vacuity class the roleForms floor below guards for check 1.
export const TOOLBOX_OWNING_SKILLS = new Set([
  'boss-build',
  'boss-epic',
  'boss-plan',
  'boss-repair',
  'boss-review',
  'bs-sweep-debt',
  'bs-sweep-mutation',
  'bs-sweep-security',
  'bs-sweep-tests',
])

// Content-taxonomy labels are applied LITERALLY, never role-mapped. Routing one
// through labelName() throws at runtime. Keeping this denylist honest is what stops
// the boss-plan label-role defect class from returning.
//
// `bug` is deliberately ABSENT. The BOS-639 plan predicted BOS-631 would delete
// `.boss-skills.json` -> trackerConfig.linear.labels.bug and listed `bug` here on that
// basis; the merged commit (ada17a5e7, "resolve taxonomy labels through config") did the
// opposite and ADDED it, and three bs-sweep skills now cite it as a mapped role. Config
// is the authority, so `bug` is a configured role and direction 2 does not apply to it.
// assertTaxonomySplit below is what caught the divergence — leave it armed.
export const CONTENT_LABELS = ['feature', 'improvement', 'docs']
const PIPELINE_LABELS = new Set([
  'agentPlan',
  'agentFriendly',
  'needsHuman',
  'agentQuestion',
  'epic',
])

// Role-resolving helpers and the trackerConfig field each reads.
export const ROLE_FIELDS = Object.freeze({
  labelName: 'labels',
  optionalLabelName: 'labels',
  stateName: 'states',
  githubLabelName: 'githubLabels',
})
const OPTIONAL_ROLE_FUNCTIONS = new Set(['optionalLabelName'])

const ROLE_FUNCTIONS = Object.keys(ROLE_FIELDS).join('|')
const ROLE_CALL = new RegExp(`\\b(${ROLE_FUNCTIONS})\\(\\s*config\\s*,\\s*'([^']*)'\\s*\\)`, 'g')
const ROLE_PLACEHOLDER = '<role>'

// An inline-code CALL citation: a code span that STARTS with a camelCase identifier
// (at least one interior uppercase) followed by `(`. The camelCase requirement is
// what removes `feat(`, `chore(`, `test(`, `init(`, `type(`.
const INLINE_CODE = /`([^`\n]+)`/g
const CALL_CITATION = /^([a-z][a-z0-9]*[A-Z][A-Za-z0-9]*)\(/

// `node <optionally-quoted path ending .mjs> <kebab verb>`. The literal `node` token
// is load-bearing — see the header.
const VERB_CITATION = /\bnode\s+(["']?)([^\s"'`]+\.mjs)\1\s+([a-z][a-z0-9]*(?:-[a-z0-9]+)*)\b/g

// A helper's own dispatch. The identifier list is measured, not guessed: bare
// `command` (plan-attachment.mjs) and `args.sub` (proof.mjs) both occur, and
// proof.mjs dispatches its most-cited verb (`run`) with `!==`, so an `===`-only
// extractor would false-flag all 18 `node scripts/proof.mjs run` citations.
const VERB_DISPATCH =
  /(?:^|[^\w.])(?:cmd|command|subcommand|sub|args\.command|args\.sub)\s*(?:===|!==)\s*'([a-z][a-z0-9]*(?:-[a-z0-9]+)*)'/g

export function findSkillFiles(root, deps = {}) {
  const fsImpl = deps.fs || fs
  const results = []
  const walk = (dir) => {
    for (const entry of fsImpl.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name)
      if (entry.isDirectory()) {
        if (EXCLUDED_DIR_NAMES.has(entry.name)) continue
        if (EXCLUDED_PATH_SEGMENTS.some((segment) => toPosix(full).includes(segment))) continue
        walk(full)
      } else if (entry.name.endsWith('.md')) {
        if (EXCLUDED_PATH_SEGMENTS.some((segment) => toPosix(full).includes(segment))) continue
        results.push(full)
      }
    }
  }
  walk(root)
  return results.sort()
}

function toPosix(value) {
  return value.split(path.sep).join('/')
}

function findModuleFiles(root, deps = {}) {
  const fsImpl = deps.fs || fs
  const results = []
  const walk = (dir) => {
    for (const entry of fsImpl.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name)
      if (entry.isDirectory()) {
        if (entry.name === 'node_modules') continue
        walk(full)
      } else if (entry.name.endsWith('.mjs') && !entry.name.endsWith('.test.mjs')) {
        results.push(full)
      }
    }
  }
  walk(root)
  return results.sort()
}

// ---------------------------------------------------------------------------
// Check 1 — tracker role citations
// ---------------------------------------------------------------------------

export function resolveRoleKeys(config) {
  const adapter = adapterFor(config, 'tracker')
  const trackerConfig = trackerConfigFor(config, adapter) ?? {}
  const keys = {}
  for (const field of Object.values(ROLE_FIELDS)) {
    keys[field] = new Set(Object.keys(trackerConfig[field] ?? {}))
  }
  return keys
}

// Form B: a `<role>` placeholder followed on the SAME line by `:` and a contiguous
// comma-separated run of inline-code tokens. Line-scoped on purpose — the run must
// not spill into the prose tail after the enumeration.
export function extractEnumeratedRun(rest) {
  const colon = rest.indexOf(':')
  if (colon === -1) return []
  let remainder = rest.slice(colon + 1)
  const first = /^[^\S\n]*`([^`\n]+)`/.exec(remainder)
  if (!first) return []
  const tokens = [first[1]]
  remainder = remainder.slice(first[0].length)
  for (;;) {
    const next = /^,[^\S\n]*`([^`\n]+)`/.exec(remainder)
    if (!next) break
    tokens.push(next[1])
    remainder = remainder.slice(next[0].length)
  }
  return tokens
}

export function extractRoleCitations(contents) {
  const citations = []
  const lines = contents.split('\n')
  lines.forEach((text, index) => {
    const line = index + 1
    ROLE_CALL.lastIndex = 0
    let match
    while ((match = ROLE_CALL.exec(text)) !== null) {
      const [, fn, role] = match
      if (role === ROLE_PLACEHOLDER) {
        for (const token of extractEnumeratedRun(text.slice(match.index + match[0].length))) {
          citations.push({ line, fn, role: token, form: 'B' })
        }
        continue
      }
      citations.push({ line, fn, role, form: 'A' })
    }
  })
  return citations
}

export function checkRoleCitations(citations, roleKeys) {
  const findings = []
  for (const { line, fn, role, form } of citations) {
    const field = ROLE_FIELDS[fn]
    if (OPTIONAL_ROLE_FUNCTIONS.has(fn)) {
      if (field === 'labels' && PIPELINE_LABELS.has(role)) {
        findings.push({
          line,
          kind: 'role-optional-pipeline',
          detail: `${fn}(config, '${role}') cites pipeline label role '${role}' — pipeline roles must resolve through labelName() (form ${form})`,
        })
      }
      continue
    }
    if (field === 'labels' && CONTENT_LABELS.includes(role)) {
      findings.push({
        line,
        kind: 'role-taxonomy',
        detail: `'${role}' is a content-taxonomy label applied literally — never route it through ${fn}() (form ${form})`,
      })
      continue
    }
    if (!roleKeys[field].has(role)) {
      findings.push({
        line,
        kind: 'role-unconfigured',
        detail: `${fn}(config, '${role}') — '${role}' is not a configured trackerConfig.${field} key (form ${form})`,
      })
    }
  }
  return findings
}

// The denylist must not rot into a no-op: if a content label ever becomes a
// configured role key, that is a taxonomy decision a human has to make, not
// something this gate should silently absorb.
export function assertTaxonomySplit(roleKeys) {
  const overlap = CONTENT_LABELS.filter((label) => roleKeys.labels.has(label))
  if (overlap.length > 0) {
    throw new Error(
      `check-skill-symbols: CONTENT_LABELS overlaps configured trackerConfig label roles: ${overlap.join(', ')}. ` +
        'Resolve the machinery-vs-taxonomy split — either drop the config key or drop it from CONTENT_LABELS.',
    )
  }
}

// ---------------------------------------------------------------------------
// Check 2 — toolbox export citations
// ---------------------------------------------------------------------------

export function parseExports(contents, label = '<memory>') {
  const names = new Set()
  for (const match of contents.matchAll(/export\s*{([^}]*)}/g)) {
    for (const raw of match[1].split(',')) {
      const entry = raw.trim()
      if (entry === '') continue
      const parts = entry.split(/\s+as\s+/)
      const name = (parts[1] ?? parts[0]).trim()
      if (name !== '' && name !== 'default') names.add(name)
    }
  }

  contents.split('\n').forEach((text, index) => {
    if (!/^export\b/.test(text)) return
    let match
    if ((match = /^export\s+(?:async\s+)?function\s+([A-Za-z_$][\w$]*)/.exec(text))) {
      names.add(match[1])
      return
    }
    if ((match = /^export\s+(?:const|let|var)\s+([A-Za-z_$][\w$]*)/.exec(text))) {
      names.add(match[1])
      return
    }
    if ((match = /^export\s+class\s+([A-Za-z_$][\w$]*)/.exec(text))) {
      names.add(match[1])
      return
    }
    if (/^export\s*{/.test(text)) return
    throw new Error(
      `check-skill-symbols: unclassifiable export at ${label}:${index + 1} — ${text.trim()}. ` +
        'Teach parseExports the new form rather than letting the index silently miss it.',
    )
  })

  return names
}

export function buildExportIndex(repoRoot, deps = {}) {
  const fsImpl = deps.fs || fs
  const names = new Set([
    ...TRACKER_CAPABILITIES,
    ...OPTIONAL_TRACKER_CAPABILITIES,
    ...OPTIONAL_TRACKER_OPERATIONS,
    ...REQUIRED_TRACKER_OPERATIONS,
  ])
  let modules = 0
  for (const root of MODULE_ROOTS) {
    const full = path.join(repoRoot, root)
    if (!fsImpl.existsSync(full)) continue
    for (const file of findModuleFiles(full, deps)) {
      modules += 1
      for (const name of parseExports(
        fsImpl.readFileSync(file, 'utf8'),
        toPosix(path.relative(repoRoot, file)),
      )) {
        names.add(name)
      }
    }
  }
  return { names, modules }
}

export function extractExportCitations(contents) {
  const citations = []
  contents.split('\n').forEach((text, index) => {
    INLINE_CODE.lastIndex = 0
    let span
    while ((span = INLINE_CODE.exec(text)) !== null) {
      const call = CALL_CITATION.exec(span[1])
      if (call) citations.push({ line: index + 1, name: call[1] })
    }
  })
  return citations
}

// ---------------------------------------------------------------------------
// Check 3 — helper CLI verbs
// ---------------------------------------------------------------------------

export function parseDispatchVerbs(contents) {
  const verbs = new Set()
  for (const match of contents.matchAll(VERB_DISPATCH)) verbs.add(match[1])
  return verbs
}

export function buildVerbIndex(repoRoot, deps = {}) {
  const fsImpl = deps.fs || fs
  // Basename union: `cli.mjs` exists at skills-toolbox/tracker/ AND
  // skills-toolbox/finalize/, and scripts/skill-extensions.mjs is a zero-dispatch
  // re-export shim whose real dispatch lives in skills-toolbox/skill-extensions.mjs.
  const verbs = new Map()
  for (const root of MODULE_ROOTS) {
    const full = path.join(repoRoot, root)
    if (!fsImpl.existsSync(full)) continue
    for (const file of findModuleFiles(full, deps)) {
      const base = path.basename(file)
      const set = verbs.get(base) ?? new Set()
      for (const verb of parseDispatchVerbs(fsImpl.readFileSync(file, 'utf8'))) set.add(verb)
      verbs.set(base, set)
    }
  }
  return verbs
}

export function extractVerbCitations(contents) {
  const citations = []
  contents.split('\n').forEach((text, index) => {
    VERB_CITATION.lastIndex = 0
    let match
    while ((match = VERB_CITATION.exec(text)) !== null) {
      citations.push({
        line: index + 1,
        script: path.posix.basename(match[2]),
        verb: match[3],
      })
    }
  })
  return citations
}

export function checkVerbCitations(citations, verbIndex) {
  const findings = []
  for (const { line, script, verb } of citations) {
    // A cited basename we do not index at all is out of scope (a repo-external
    // helper, a doc example). Ignore it.
    if (!verbIndex.has(script)) continue
    const verbs = verbIndex.get(script)
    if (verbs.size === 0) {
      findings.push({
        line,
        kind: 'verb-index-empty',
        detail: `${script} is cited with verbs but no dispatch verb could be derived from it — the dispatch idiom changed`,
      })
      continue
    }
    if (!verbs.has(verb)) {
      findings.push({
        line,
        kind: 'verb-unknown',
        detail: `node ${script} ${verb} — '${verb}' is not a verb ${script} dispatches (known: ${[...verbs].sort().join(', ')})`,
      })
    }
  }
  return findings
}

// ---------------------------------------------------------------------------
// Orchestration
// ---------------------------------------------------------------------------

// Which skills vendor a `toolbox/`, read from the tree rather than from a list someone
// has to remember to update. findSkillFiles skips `toolbox/` when collecting prose, but
// the directory's EXISTENCE is what ownership means, and that is still observable here.
export function discoverToolboxOwners(repoRoot, deps = {}) {
  const fsImpl = deps.fs || fs
  const owners = new Set()
  for (const root of SKILL_ROOTS) {
    const full = path.join(repoRoot, root)
    if (!fsImpl.existsSync(full)) continue
    for (const entry of fsImpl.readdirSync(full, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue
      if (fsImpl.existsSync(path.join(full, entry.name, 'toolbox'))) owners.add(entry.name)
    }
  }
  return owners
}

function skillNameFor(relativePath) {
  for (const root of SKILL_ROOTS) {
    if (relativePath.startsWith(`${root}/`))
      return relativePath.slice(root.length + 1).split('/')[0]
  }
  return null
}

export function checkSkillSymbols(repoRoot, deps = {}) {
  const fsImpl = deps.fs || fs
  const config = deps.config ?? loadSkillConfig({ cwd: repoRoot })
  const roleKeys = resolveRoleKeys(config)
  assertTaxonomySplit(roleKeys)

  const { names: exportNames, modules } = buildExportIndex(repoRoot, deps)
  const verbIndex = buildVerbIndex(repoRoot, deps)
  const toolboxOwners = discoverToolboxOwners(repoRoot, deps)

  const findings = []
  const roleForms = { A: 0, B: 0 }
  let scanned = 0

  for (const root of SKILL_ROOTS) {
    const full = path.join(repoRoot, root)
    if (!fsImpl.existsSync(full)) continue
    for (const file of findSkillFiles(full, deps)) {
      scanned += 1
      const relative = toPosix(path.relative(repoRoot, file))
      const contents = fsImpl.readFileSync(file, 'utf8')
      const record = ({ line, kind, detail }) =>
        findings.push({ file: relative, line, kind, detail })

      const roleCitations = extractRoleCitations(contents)
      for (const { form } of roleCitations) roleForms[form] += 1
      checkRoleCitations(roleCitations, roleKeys).forEach(record)

      if (toolboxOwners.has(skillNameFor(relative))) {
        for (const { line, name } of extractExportCitations(contents)) {
          if (!exportNames.has(name)) {
            record({
              line,
              kind: 'export-unknown',
              detail: `${name}() is not exported by skills-toolbox/** or scripts/**, and is not a tracker capability/operation`,
            })
          }
        }
      }

      checkVerbCitations(extractVerbCitations(contents), verbIndex).forEach(record)
    }
  }

  // Vacuity floor for check 1. Both role forms are extracted line-scoped, so an
  // ordinary prose re-wrap can silently drop every citation of a form and leave the
  // check passing on zero input — the exact defect this gate exists to catch would
  // then slip through with no signal. Form B in particular is populated by a single
  // long line today, one editor reflow away from invisible.
  // Default-on so the live run and every future caller are fail-closed; the narrow
  // single-dimension fixtures in the test file opt out explicitly rather than each
  // carrying role prose they are not about.
  for (const [form, count] of Object.entries(roleForms)) {
    if (count === 0 && deps.requireRoleForms !== false) {
      findings.push({
        file: SKILL_ROOTS.join(', '),
        line: 0,
        kind: 'role-check-vacuous',
        detail: `check 1 extracted zero form ${form} role citations across the skill tree — the citations are line-scoped, so a prose re-wrap most likely made them invisible rather than the prose genuinely losing them`,
      })
    }
  }

  // Drift tripwire for check 2's scope, in the direction derivation cannot self-detect.
  // A skill that STARTS vendoring a toolbox now widens the scope on its own, so that
  // half needs no list. The dangerous half is derivation returning too little: if the
  // walk stops seeing the toolboxes it should, check 2 silently narrows — to nothing at
  // the limit — and still exits 0. Comparing against the pinned set turns that into a
  // finding. Default-on so the live run is fail-closed; fixtures that are about some
  // other dimension, and so carry none of the 9 real skills, opt out explicitly.
  if (deps.requireToolboxOwnerPin !== false) {
    const added = [...toolboxOwners].filter((name) => !TOOLBOX_OWNING_SKILLS.has(name)).sort()
    const missing = [...TOOLBOX_OWNING_SKILLS].filter((name) => !toolboxOwners.has(name)).sort()
    if (added.length > 0 || missing.length > 0) {
      const parts = []
      if (added.length > 0) parts.push(`newly vendoring a toolbox: ${added.join(', ')}`)
      if (missing.length > 0) parts.push(`no longer discovered: ${missing.join(', ')}`)
      findings.push({
        file: SKILL_ROOTS.join(', '),
        line: 0,
        kind: 'toolbox-owner-drift',
        detail: `the toolbox-owning skills discovered in the tree differ from TOOLBOX_OWNING_SKILLS (${parts.join('; ')}) — update the pin if the tree is right, and treat a shrinking set as check 2 having narrowed its own scope`,
      })
    }
  }

  findings.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line)
  return { findings, scanned, modules, exportNames: exportNames.size, roleForms, toolboxOwners }
}

function main() {
  const repoRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
  let result
  try {
    result = checkSkillSymbols(repoRoot)
  } catch (error) {
    console.error(error.message)
    process.exit(1)
  }
  if (result.findings.length > 0) {
    console.error('Skill prose names symbols that do not exist:')
    for (const { file, line, kind, detail } of result.findings) {
      console.error(`${file}:${line}  ${kind}  ${detail}`)
    }
    process.exit(1)
  }
  console.log(
    `Skill symbol contract OK — ${result.scanned} skill markdown files checked against ` +
      `${result.exportNames} exports from ${result.modules} modules.`,
  )
}

if (isMainModule(import.meta.url)) main()
