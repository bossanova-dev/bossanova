#!/usr/bin/env node

// Generates <bin-dir>/plugins.sum: the SHA-256 of every bossd-plugin-* binary in
// the directory, in the "<hex>  <basename>" format that bossd's plugin
// verification expects (lib/bossalib/config/pluginsum.go). On release builds
// bossd refuses to exec any discovered plugin whose hash is absent from — or
// mismatched against — this manifest, and fails closed when the manifest is
// missing entirely (see lib/bossalib/config/config.go, docs/plans/BOS-27-*.md).
// So a release that ships the enforcing daemon without this file would load zero
// agent runners and could not start sessions; `make plugins` runs this so the
// manifest is always built next to the binaries.
//
// Node builtins only (matches the repo script convention). Platform-suffixed
// cross-compiles (-darwin-arm64 etc.) and the manifest itself are excluded,
// mirroring scanForPlugins. Exercised by scripts/gen-plugin-sums.test.mjs and
// runnable via `node scripts/gen-plugin-sums.mjs <bin-dir>`.

import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const PLATFORM_SUFFIXES = ['-darwin-arm64', '-darwin-amd64', '-linux-arm64', '-linux-amd64']

export function pluginSumLines(dir, listdir = readdirSync, read = readFileSync) {
  const names = listdir(dir)
    .filter((n) => n.startsWith('bossd-plugin-'))
    .filter((n) => n !== 'plugins.sum')
    .filter((n) => !PLATFORM_SUFFIXES.some((s) => n.endsWith(s)))
    .sort()
  return names.map((n) => {
    const hash = createHash('sha256')
      .update(read(join(dir, n)))
      .digest('hex')
    return `${hash}  ${n}`
  })
}

function main() {
  const dir = process.argv[2]
  if (!dir) {
    console.error('usage: gen-plugin-sums.mjs <bin-dir>')
    process.exit(1)
  }
  const lines = pluginSumLines(dir)
  const body =
    '# bossd plugin checksums (generated by scripts/gen-plugin-sums.mjs)\n' +
    lines.join('\n') +
    '\n'
  writeFileSync(join(dir, 'plugins.sum'), body)
  console.log(`wrote ${lines.length} plugin checksums to ${join(dir, 'plugins.sum')}`)
}

import { isMainModule } from '../skills-toolbox/main-module.mjs'

if (isMainModule(import.meta.url)) {
  main()
}
