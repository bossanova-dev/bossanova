import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import test from 'node:test'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const cli = path.join(root, 'scripts/guards/boundaries-doc.mjs')
function fixture(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'boundaries-doc-'))
  t.after(() => fs.rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 }))
  fs.mkdirSync(path.join(dir, 'scripts/guards/registry'), { recursive: true })
  fs.writeFileSync(path.join(dir, 'baseline.json'), '["first", "second"]\n')
  addRecord(dir, 'sample', { boundary: true, baseline: 'baseline.json' })
  addRecord(dir, 'ordinary')
  return dir
}
function addRecord(dir, id, extra = {}) {
  const record = {
    id,
    rule: `${id} rule.`,
    command: `node ${id}.mjs`,
    wiring: { make: 'lint-scripts', ci: { workflow: 'test-scripts.yml', job: 'scripts' } },
    scans: ['scripts/**'],
    baseline: null,
    proof: { file: 'sample.test.mjs', test: 'proof' },
    ...extra,
  }
  fs.writeFileSync(
    path.join(dir, `scripts/guards/registry/${id}.mjs`),
    `export default ${JSON.stringify(record)}\n`,
  )
}
const out = (dir) => path.join(dir, 'boundaries.md')
const run = (dir, mode) =>
  spawnSync(process.execPath, [cli, mode, '--root', dir, '--out', out(dir)], { encoding: 'utf8' })
function write(dir) {
  const result = run(dir, '--write')
  assert.equal(result.status, 0, result.stderr)
}
test('--check fails on a hand-edited boundaries.md', (t) => {
  const dir = fixture(t)
  write(dir)
  fs.appendFileSync(out(dir), '\nAn edit.\n')
  const result = run(dir, '--check')
  assert.equal(result.status, 1)
  assert.match(result.stderr, /^-/m)
  assert.match(result.stderr, /Run: make boundaries-doc-update/)
})
test('--check detects changed baseline counts and unregenerated boundary records', (t) => {
  const dir = fixture(t)
  write(dir)
  fs.writeFileSync(path.join(dir, 'baseline.json'), '["first"]\n')
  assert.equal(run(dir, '--check').status, 1)
  write(dir)
  addRecord(dir, 'added', { boundary: true })
  assert.equal(run(dir, '--check').status, 1)
  write(dir)
  assert.equal(run(dir, '--check').status, 0)
})
test('--write is idempotent and only boundary records appear', (t) => {
  const dir = fixture(t)
  write(dir)
  const bytes = fs.readFileSync(out(dir), 'utf8')
  assert.match(bytes, /sample rule/)
  assert.doesNotMatch(bytes, /ordinary rule/)
  write(dir)
  assert.equal(fs.readFileSync(out(dir), 'utf8'), bytes)
  assert.equal(run(dir, '--check').status, 0)
})
test('object baselines count their top-level offenders', (t) => {
  const dir = fixture(t)
  fs.writeFileSync(path.join(dir, 'object.json'), '{"one": [], "two": ["a", "b"]}\n')
  addRecord(dir, 'object', { boundary: true, baseline: 'object.json', baselineFormat: 'json' })
  write(dir)
  assert.match(fs.readFileSync(out(dir), 'utf8'), /`object.json` \| 2 \|/)
})
test('malformed and unreadable baselines fail both modes', (t) => {
  const dir = fixture(t)
  for (const bytes of ['bad json', '{}', '["duplicate", "duplicate"]']) {
    fs.writeFileSync(path.join(dir, 'baseline.json'), bytes)
    assert.equal(run(dir, '--write').status, 1)
    assert.equal(run(dir, '--check').status, 1)
  }
  fs.unlinkSync(path.join(dir, 'baseline.json'))
  assert.equal(run(dir, '--write').status, 1)
  addRecord(dir, 'object', { boundary: true, baseline: 'object.json', baselineFormat: 'json' })
  fs.writeFileSync(path.join(dir, 'object.json'), '[]')
  assert.equal(run(dir, '--write').status, 1)
})
test('generated bytes pass prettier --check', (t) => {
  const dir = fixture(t)
  write(dir)
  const result = spawnSync(
    path.join(root, 'node_modules/.bin/prettier'),
    ['--check', '--config', path.join(root, '.prettierrc'), out(dir)],
    { encoding: 'utf8' },
  )
  assert.equal(result.status, 0, result.stdout + result.stderr)
})
