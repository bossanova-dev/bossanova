const entitiesFile = path.resolve('docs/structure/entities.yaml')
function fixture(t, files) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'entity-names-'))
  t.after(() => fs.rmSync(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 }))
  for (const [file, text] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true })
    fs.writeFileSync(path.join(root, file), text)
  }
  fs.writeFileSync(path.join(root, 'baseline.json'), '[]\n')
  execFileSync('git', ['init', '-q'], { cwd: root })
  execFileSync('git', ['add', '--', ...Object.keys(files)], { cwd: root })
  return root
}
function check(root) {
  return checkEntityNames({ repoRoot: root, entitiesFile, baselinePath: 'baseline.json' })
}
test('entity-names fails a seeded ClaudeChat Go declaration and names AgentChat', (t) => {
  const result = check(fixture(t, { 'x.go': 'package x\ntype ClaudeChatThing struct{}\n' }))
  assert.match(result.failures.join('\n'), /go:x.go:ClaudeChatThing:.*AgentChat/)
})
