test('word boundaries, plurals, qualifiers, position and paths constrain bans', () => {
  const run = { match: 'Run', position: 'after-verb' }
  for (const name of ['StartRun', 'GetRunCost', 'RecordRunTelemetry'])
    assert.ok(matchesBan(name, run, ['Start', 'Get', 'Record'], 'x'))
  for (const name of ['CheckRun', 'DryRun', 'LastRunAt'])
    assert.equal(matchesBan(name, run, ['Start'], 'x'), false)
  assert.ok(matchesBan('ListAccounts', { match: 'Account' }, [], 'x'))
  assert.equal(
    matchesBan('AgentAccount', { match: 'Account', except_after: ['Agent', 'Cloud'] }, [], 'x'),
    false,
  )
  assert.equal(matchesBan('Accounts', { match: 'accounts', position: 'whole' }, [], 'x'), true)
  assert.equal(matchesBan('MyAccounts', { match: 'accounts', position: 'whole' }, [], 'x'), false)
  assert.equal(matchesBan('GithubEvents', { match: 'Github', kind: 'text' }, [], 'x'), true)
  assert.equal(matchesBan('Githubber', { match: 'Github', kind: 'text' }, [], 'x'), false)
  assert.equal(
    matchesBan(
      'Account',
      { match: 'Account', paths: ['services/**'], exclude_paths: ['services/bosso/**'] },
      [],
      'services/bosso/x.go',
    ),
    false,
  )
  assert.equal(
    matchesBan('Account', { match: 'Account', paths: ['services/**'] }, [], 'lib/x.go'),
    false,
  )
  assert.ok(matchesBan('claude_chats', { match: 'ClaudeChat' }, [], 'x'))
})
test('Go scanner handles methods, generics, grouped declarations and ignores literals and fields', () => {
  const source =
    'package x\n/*\nfunc GithubFake() {}\n*/\nvar Text = `\nfunc GithubRaw() {}\n`\ntype (\n GithubType[T any] struct { GithubField int }\n GithubInterface interface { GithubMethod() }\n)\nconst (\n GithubConst = 1\n GithubOther\n)\nvar GithubA, GithubB int\nfunc (x *GithubType[T]) GithubMethod() {}\nfunc GithubFunction[T any]() {}\n'
  assert.deepEqual(
    goDeclarations(source).map((x) => x.name),
    [
      'Text',
      'GithubType',
      'GithubInterface',
      'GithubConst',
      'GithubOther',
      'GithubA',
      'GithubB',
      'GithubType.GithubMethod',
      'GithubFunction',
    ],
  )
})
test('Go excludes tests, gen and generated headers; inline exception suppresses one declaration', (t) => {
  const root = fixture(t, {
    'x_test.go': 'package x\ntype ClaudeChatTest int',
    'gen/x.go': 'package x\ntype ClaudeChatGen int',
    'generated.go': '// Code generated by x. DO NOT EDIT.\npackage x\ntype ClaudeChatGenerated int',
    'x.go':
      'package x\n// guard-exception(entity-names): compatibility; expires 2099-01-01\ntype ClaudeChatAllowed int\ntype ClaudeChatBad int',
  })
  assert.equal(check(root).failures.length, 1)
  assert.match(check(root).failures[0], /ClaudeChatBad/)
})
test('TS scanner reads export declarations and exported aliases, excluding strings and locals', () => {
  assert.deepEqual(
    tsDeclarations(
      'const s="export type GithubFake = x"; export { a as GithubY }; export default async function GithubF() {} export abstract class GithubClass {} export const GithubA=1, GithubB=2;',
    ).map((x) => x.name),
    ['GithubY', 'GithubF', 'GithubClass', 'GithubA', 'GithubB'],
  )
})
test('TS generated files are excluded', (t) => {
  const root = fixture(t, {
    'services/web/src/gen/x.ts': 'export type GithubBad = string',
    'services/web/src/x.ts': 'export { a as GithubY }',
  })
  assert.equal(check(root).failures.length, 1)
  assert.match(check(root).failures[0], /GithubY/)
})
test('migration replay checks final tables separately and ignores Down', () => {
  const tables = replayTables([
    '-- +goose Up\nCREATE TABLE accounts(x int); CREATE TABLE claude_chats(x int);\n-- +goose Down\nDROP TABLE accounts;',
    '-- +goose Up\nALTER TABLE claude_chats RENAME TO agent_chats; CREATE TABLE attempts(x int); DROP TABLE attempts;',
  ])
  assert.deepEqual([...tables].sort(), ['accounts', 'agent_chats'])
})
test('baseline round trips and rejects new and stale offenders', (t) => {
  const root = fixture(t, { 'x.go': 'package x\ntype ClaudeChatThing int' })
  assert.equal(check(root).failures.length, 1)
  const result = checkEntityNames({
    repoRoot: root,
    entitiesFile,
    baselinePath: 'baseline.json',
    writeBaseline: true,
  })
  assert.deepEqual(result.failures, [])
  assert.deepEqual(check(root).failures, [])
  fs.writeFileSync(path.join(root, 'x.go'), 'package x\ntype AgentChatThing int')
  assert.match(check(root).failures.join('\n'), /no longer occurs/)
})
