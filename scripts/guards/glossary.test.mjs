import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import test from 'node:test'
import { fileURLToPath } from 'node:url'
import { loadEntities } from './entities.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const entities = path.join(root, 'docs/structure/entities.yaml')
const cli = path.join(root, 'scripts/guards/glossary.mjs')
const run = (out, mode) =>
  spawnSync(process.execPath, [cli, mode, '--entities', entities, '--out', out], {
    encoding: 'utf8',
  })
function fixture(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'glossary-'))
  t.after(() => fs.rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 }))
  return path.join(dir, 'glossary.md')
}
test('--check fails on a hand-edited glossary.md', (t) => {
  const out = fixture(t)
  assert.equal(run(out, '--write').status, 0)
  fs.appendFileSync(out, '\nAn edit.\n')
  const result = run(out, '--check')
  assert.equal(result.status, 1)
  assert.match(result.stderr, /^-/m)
})
test('--check passes after --write and regeneration is idempotent', (t) => {
  const out = fixture(t)
  assert.equal(run(out, '--write').status, 0)
  const before = fs.readFileSync(out, 'utf8')
  assert.equal(run(out, '--check').status, 0)
  assert.equal(run(out, '--write').status, 0)
  assert.equal(fs.readFileSync(out, 'utf8'), before)
})
test('generated bytes pass prettier --check', (t) => {
  const out = fixture(t)
  assert.equal(run(out, '--write').status, 0)
  const result = spawnSync(
    path.join(root, 'node_modules/.bin/prettier'),
    ['--check', '--config', path.join(root, '.prettierrc'), out],
    { encoding: 'utf8' },
  )
  assert.equal(result.status, 0, result.stdout + result.stderr)
})
test('the entity data covers all canonical entities and leaves Daemon unbanned', () => {
  const result = loadEntities(entities)
  assert.deepEqual(result.errors, [])
  assert.deepEqual(
    result.entities.map((e) => e.code).sort(),
    [
      'Session',
      'AgentChat',
      'AgentRun',
      'FixAttempt',
      'ResumeAttempt',
      'TriggerInvocation',
      'TriggerLaunch',
      'Trigger',
      'Repo',
      'Organization',
      'AgentAccount',
      'CloudAccount',
      'Workflow',
      'CronJob',
      'Note',
      'Webhook',
      'GitHubCallback',
      'User',
      'Daemon',
      'Broadcast',
      'BroadcastSubscription',
      'OrganizationMember',
      'OrganizationNote',
      'SessionWebhookDelivery',
    ].sort(),
  )
  assert.deepEqual(result.entities.find((e) => e.code === 'Daemon').bans, [])
})
test('entity loader rejects malformed structures and warns about extra fields', (t) => {
  const file = fixture(t)
  const valid = {
    id: 'sample',
    noun: 'sample',
    code: 'Sample',
    table: null,
    proto: null,
    ui: null,
    definition: 'A sample.',
    bans: [],
  }
  const load = (data) => {
    fs.writeFileSync(file, JSON.stringify(data))
    return loadEntities(file)
  }
  assert.equal(load({ verbs: ['Get'], entities: [valid] }).errors.length, 0)
  for (const entity of [
    { ...valid, noun: undefined },
    { ...valid, bans: [{ match: 'Old', layers: ['invalid'] }] },
    { ...valid, bans: [{ match: 'Old', layers: ['go'], position: 'invalid' }] },
  ]) {
    assert.ok(load({ verbs: ['Get'], entities: [entity] }).errors.length > 0)
  }
  assert.ok(load({ verbs: ['Get'], entities: [valid, valid] }).errors.length > 0)
  assert.equal(load({ verbs: ['Get'], entities: [{ ...valid, future: true }] }).warnings.length, 1)
  fs.writeFileSync(file, 'entities: [')
  assert.ok(loadEntities(file).errors.length > 0)
})
test('the CLI rejects ambiguous modes and unknown flags', (t) => {
  const out = fixture(t)
  assert.equal(spawnSync(process.execPath, [cli], { encoding: 'utf8' }).status, 2)
  assert.notEqual(
    spawnSync(process.execPath, [cli, '--write', '--check', '--out', out], { encoding: 'utf8' })
      .status,
    0,
  )
  assert.notEqual(spawnSync(process.execPath, [cli, '--unknown'], { encoding: 'utf8' }).status, 0)
})
