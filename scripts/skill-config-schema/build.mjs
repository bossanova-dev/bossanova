#!/usr/bin/env node

// guard-id: skill-config-validator-fresh

// Compiles scripts/skill-config-schema/schema.mjs into the dependency-free validator the vendored
// toolboxes import (skills-toolbox/skill-config-validate.generated.mjs): ajv standalone code,
// bundled and minified by esbuild with no externals, so the output runs under plain node with no
// node_modules anywhere above it.
//
//   node scripts/skill-config-schema/build.mjs           regenerate the validator
//   node scripts/skill-config-schema/build.mjs --check   fail when the committed file is stale
//
// --schema and --out override the two paths (tests point them at fixtures).

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { parseArgs } from 'node:util'

import AjvModule from 'ajv'
import standaloneModule from 'ajv/dist/standalone/index.js'
import { build } from 'esbuild'

import { isMainModule } from '../../skills-toolbox/main-module.mjs'

// ajv is CommonJS, so a default import is module.exports; its `default` is the typed export.
const Ajv = AjvModule.default
const standaloneCode = standaloneModule.default

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')

export const SCHEMA_FILE = 'scripts/skill-config-schema/schema.mjs'
export const OUTPUT_FILE = 'skills-toolbox/skill-config-validate.generated.mjs'
export const UPDATE_COMMAND = 'make skill-config-validator'
export const ANNOTATION_KEYWORDS = ['x-msg', 'x-unknown']

const HEADER = [
  // No repo-root path here: the file ships inside globally installed cores, where it does not exist.
  '// Code generated by skill-config-schema/build.mjs from skill-config-schema/schema.mjs. DO NOT EDIT.',
  `// Regenerate with \`${UPDATE_COMMAND}\`. Exports \`validate\` (ajv standalone, allErrors) and`,
  '// `schema` (the source schema, for the x-msg / x-unknown annotations skill-config.mjs reads).',
  '',
].join('\n')

// Each ajv runtime helper carries `<fn>.code = 'require("ajv/dist/runtime/…")'`, a string ajv's
// code generator reads at compile time. Dead in the bundle, and it would leave a `require` token in
// a file that must have none, so it is dropped as the helper is loaded.
const stripRuntimeCodeStrings = {
  name: 'strip-ajv-runtime-code-strings',
  setup(builder) {
    builder.onLoad({ filter: /[\\/]ajv[\\/]dist[\\/]runtime[\\/][^\\/]+\.js$/ }, (args) => ({
      contents: fs.readFileSync(args.path, 'utf8').replace(/^\w+\.code = .*$/gm, ''),
      loader: 'js',
    }))
  },
}

/**
 * The generated module's full text for `schema`.
 *
 * @param {object} schema
 * @returns {Promise<string>}
 */
export async function buildValidator(schema) {
  const ajv = new Ajv({
    allErrors: true,
    strict: true,
    // `review` deliberately carries object keywords without `type: object` (see schema.mjs).
    strictTypes: false,
    code: { source: true, esm: true },
  })
  ajv.addVocabulary(ANNOTATION_KEYWORDS)
  const code = standaloneCode(ajv, ajv.compile(schema))
  // ajv embeds the root schema as its first `const schemaN`; re-export it rather than a second copy.
  const rootSchema = /\bconst (schema\d+) = /.exec(code)?.[1]
  if (!rootSchema) throw new Error('ajv standalone output embeds no root schema constant')
  const source = `${code}\nexport const schema = ${rootSchema};\n`
  const result = await build({
    stdin: { contents: source, resolveDir: REPO_ROOT, sourcefile: 'skill-config-validate.mjs' },
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    minify: true,
    legalComments: 'none',
    write: false,
    logLevel: 'silent',
    plugins: [stripRuntimeCodeStrings],
  })
  return `${HEADER}${result.outputFiles[0].text}`
}

async function loadSchema(schemaPath) {
  const mod = await import(pathToFileURL(path.resolve(schemaPath)).href)
  if (!mod.schema || typeof mod.schema !== 'object') {
    throw new Error(`${schemaPath} must export a \`schema\` object`)
  }
  return mod.schema
}

/**
 * Regenerate, or compare against, the committed validator.
 *
 * @param {{check?: boolean, schemaPath?: string, outPath?: string}} [options]
 * @returns {Promise<{ok: boolean, message: string}>}
 */
export async function run({
  check = false,
  schemaPath = path.join(REPO_ROOT, SCHEMA_FILE),
  outPath = path.join(REPO_ROOT, OUTPUT_FILE),
} = {}) {
  const expected = await buildValidator(await loadSchema(schemaPath))
  if (!check) {
    fs.writeFileSync(outPath, expected)
    return { ok: true, message: `wrote ${path.relative(REPO_ROOT, outPath)}` }
  }
  let current = null
  try {
    current = fs.readFileSync(outPath, 'utf8')
  } catch {
    // An absent file is stale.
  }
  if (current !== expected) {
    return {
      ok: false,
      message: `${path.relative(REPO_ROOT, outPath)} is stale against ${path.relative(REPO_ROOT, schemaPath)}; regenerate with \`${UPDATE_COMMAND}\``,
    }
  }
  return { ok: true, message: `${path.relative(REPO_ROOT, outPath)} is up to date` }
}

if (isMainModule(import.meta.url)) {
  const { values } = parseArgs({
    options: {
      check: { type: 'boolean', default: false },
      schema: { type: 'string' },
      out: { type: 'string' },
    },
    allowPositionals: false,
    strict: true,
  })
  const result = await run({
    check: values.check,
    ...(values.schema ? { schemaPath: values.schema } : {}),
    ...(values.out ? { outPath: values.out } : {}),
  })
  if (!result.ok) {
    console.error(result.message)
    process.exit(1)
  }
  console.log(result.message)
}
