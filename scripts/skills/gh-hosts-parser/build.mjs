#!/usr/bin/env node
// guard-id: gh-hosts-parser-fresh
import fs from 'node:fs/promises'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'
import { build } from 'esbuild'
import { isMainModule } from '../../../skills-toolbox/main-module.mjs'

const directory = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(directory, '../../..')
export const OUTPUT_FILE = path.join(root, 'skills-toolbox/ci/gh-hosts.generated.cjs')

export async function buildParser() {
  const packageFile = createRequire(import.meta.url).resolve('yaml/package.json')
  const { version } = JSON.parse(await fs.readFile(packageFile, 'utf8'))
  const license = await fs.readFile(path.join(path.dirname(packageFile), 'LICENSE'), 'utf8')
  const result = await build({
    entryPoints: [path.join(directory, 'keys.mjs')],
    bundle: true,
    platform: 'neutral',
    format: 'cjs',
    minify: true,
    legalComments: 'none',
    write: false,
    metafile: true,
    logLevel: 'silent',
  })
  if (Object.values(result.metafile.outputs).some((output) => output.imports.length))
    throw new Error('portable host parser must have no external imports')
  return [
    '// Code generated by gh-hosts-parser/build.mjs. DO NOT EDIT.',
    `// Bundled yaml@${version}; no runtime dependencies.`,
    '/*',
    license.trimEnd(),
    '*/',
    result.outputFiles[0].text,
  ].join('\n')
}

/** @param {{check?: boolean, outPath?: string}} [options] */
export async function run({ check = false, outPath = OUTPUT_FILE } = {}) {
  const expected = await buildParser()
  let actual
  try {
    actual = await fs.readFile(outPath, 'utf8')
  } catch (error) {
    if (error.code !== 'ENOENT') throw error
  }
  const changed = actual !== expected
  if (check)
    return {
      ok: !changed,
      changed,
      message: changed ? 'gh host parser is stale; regenerate it' : 'gh host parser is current',
    }
  if (changed) await fs.writeFile(outPath, expected)
  return {
    ok: true,
    changed,
    message: changed ? 'generated gh host parser' : 'gh host parser is current',
  }
}

if (isMainModule(import.meta.url)) {
  try {
    const { values } = parseArgs({
      options: { check: { type: 'boolean' }, out: { type: 'string' } },
      strict: true,
    })
    const result = await run({ check: values.check, outPath: values.out })
    ;(result.ok ? console.log : console.error)(result.message)
    process.exitCode = result.ok ? 0 : 1
  } catch {
    console.error('could not build portable gh host parser')
    process.exitCode = 1
  }
}
