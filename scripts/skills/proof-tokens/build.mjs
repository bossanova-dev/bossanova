#!/usr/bin/env node

// Generates the proof page's theme tokens (skills-toolbox/verify/verify-proof-tokens.mjs) from the
// canonical design tokens in lib/ui-tokens/index.css. The page ships inside installed cores, where
// lib/ui-tokens does not exist, so the tokens are copied in as a module rather than imported.
//
//   node scripts/skills/proof-tokens/build.mjs           regenerate the module
//   node scripts/skills/proof-tokens/build.mjs --check   fail when the committed module is stale
//
// --css and --out override the two paths (tests point them at fixtures).

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'

import { isMainModule } from '../../../skills-toolbox/main-module.mjs'

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..')

export const CSS_FILE = 'lib/ui-tokens/index.css'
export const OUTPUT_FILE = 'skills-toolbox/verify/verify-proof-tokens.mjs'
export const UPDATE_COMMAND = 'make proof-tokens'

/**
 * The custom properties declared in the first block that opens with `selector {`.
 * @param {string} css comment-free CSS @param {string} selector @returns {[string, string][]}
 */
function block(css, selector) {
  const start = css.indexOf(`${selector} {`)
  if (start < 0) throw new Error(`${CSS_FILE} has no \`${selector} {\` block`)
  const body = css.slice(start + selector.length + 2, css.indexOf('}', start))
  const props = [...body.matchAll(/(--[\w-]+)\s*:\s*([^;]+)(?:;|$)/g)].map(
    ([, name, value]) =>
      /** @type {[string, string]} */ ([name, value.replace(/\s+/g, ' ').trim()]),
  )
  if (!props.length) throw new Error(`${CSS_FILE} \`${selector}\` declares no tokens`)
  return props
}

/**
 * The generated module's text: dark on `:root`, light when the system prefers it and the page
 * names no theme, and either one forced by `data-theme`.
 * @param {string} css
 */
export function buildTokens(css) {
  const clean = css.replace(/\/\*[\s\S]*?\*\//g, '')
  const decl = (/** @type {[string, string][]} */ props) =>
    props.map(([name, value]) => `${name}:${value}`).join(';')
  const dark = decl(block(clean, ':root'))
  const light = decl(block(clean, ":root[data-theme='light']"))
  const sheet = [
    `:root{${dark};color-scheme:dark}`,
    `@media (prefers-color-scheme:light){:root:not([data-theme]){${light};color-scheme:light}}`,
    `:root[data-theme="light"]{${light};color-scheme:light}`,
    ':root[data-theme="dark"]{color-scheme:dark}',
  ].join('\n')
  if (/[`\\]|\$\{/.test(sheet))
    throw new Error(`${CSS_FILE} tokens hold a backtick, backslash or \`\${\``)
  return [
    '// Code generated by proof-tokens/build.mjs from the ui-tokens index.css. DO NOT EDIT.',
    `// Regenerate with \`${UPDATE_COMMAND}\`.`,
    '',
    '/** The proof page theme: the design tokens, dark by default, light by system or `data-theme`. */',
    // A template literal, which prettier leaves as written; the sheet has no backtick or `${`.
    `export const PROOF_TOKENS = \`${sheet}\``,
    '',
  ].join('\n')
}

/**
 * Regenerate, or compare against, the committed module.
 * @param {{check?: boolean, cssPath?: string, outPath?: string}} [options]
 * @returns {{ok: boolean, message: string}}
 */
export function run({
  check = false,
  cssPath = path.join(REPO_ROOT, CSS_FILE),
  outPath = path.join(REPO_ROOT, OUTPUT_FILE),
} = {}) {
  const expected = buildTokens(fs.readFileSync(cssPath, 'utf8'))
  const out = path.relative(REPO_ROOT, outPath)
  if (!check) {
    fs.writeFileSync(outPath, expected)
    return { ok: true, message: `wrote ${out}` }
  }
  let current = null
  try {
    current = fs.readFileSync(outPath, 'utf8')
  } catch {
    // An absent module is stale.
  }
  return current === expected
    ? { ok: true, message: `${out} is up to date` }
    : {
        ok: false,
        message: `${out} is stale against ${path.relative(REPO_ROOT, cssPath)}; regenerate with \`${UPDATE_COMMAND}\``,
      }
}

if (isMainModule(import.meta.url)) {
  const { values } = parseArgs({
    options: {
      check: { type: 'boolean', default: false },
      css: { type: 'string' },
      out: { type: 'string' },
    },
    allowPositionals: false,
    strict: true,
  })
  const result = run({
    check: values.check,
    ...(values.css ? { cssPath: path.resolve(values.css) } : {}),
    ...(values.out ? { outPath: path.resolve(values.out) } : {}),
  })
  if (result.ok) console.log(result.message)
  else {
    console.error(result.message)
    process.exitCode = 1
  }
}
