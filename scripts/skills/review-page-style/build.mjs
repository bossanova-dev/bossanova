#!/usr/bin/env node

// Generates the web app's copy of the hosted review page's stylesheet
// (services/web/src/features/sessions/lib/reviewPageStyle.ts) from PROOF_STYLE in
// skills-toolbox/verify/verify-proof-style.mjs. The app shows a review page that was never
// published inside a shadow root, so the page's document selectors become the shadow host and its
// width breakpoints become container queries on the host. Every other rule is the hosted page's.
//
//   node scripts/skills/review-page-style/build.mjs           regenerate the module
//   node scripts/skills/review-page-style/build.mjs --check   fail when the committed module is stale
//
// --out overrides the output path (tests point it at a fixture).

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'

import { isMainModule } from '../../../skills-toolbox/main-module.mjs'
import { PROOF_STYLE } from '../../../skills-toolbox/verify/verify-proof-style.mjs'

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..')

export const OUTPUT_FILE = 'services/web/src/features/sessions/lib/reviewPageStyle.ts'
export const UPDATE_COMMAND = 'make review-page-style'

/** Each document selector the page uses, as the shadow host selector that stands in for it. */
const HOST_SELECTORS = Object.freeze([
  [':root[data-theme="light"]{', ':host([data-theme="light"]){'],
  [':root[data-theme="dark"]{', ':host([data-theme="dark"]){'],
  [':root:not([data-theme]){', ':host(:not([data-theme])){'],
  [':root{', ':host{'],
  ['\nhtml{', '\n:host{'],
  ['\nbody{', '\n:host{'],
  ['\nbody.lb-open{', '\n:host(.lb-open){'],
])

/**
 * The page stylesheet for a shadow root whose host is the page. Throws when the page gains a
 * document selector or viewport query this does not map, so the copy never silently differs.
 * @param {string} style
 */
export function shadowStyle(style) {
  let sheet = style
  for (const [from, to] of HOST_SELECTORS) sheet = sheet.replaceAll(from, to)
  sheet = sheet.replace(/@media \(max-width:(\d+)px\)/g, '@container (max-width:$1px)')
  const left = /(^|[\s,{}>+~])(:root|html|body)\b|@media \((?:max|min)-width/.exec(sheet)
  if (left)
    throw new Error(`PROOF_STYLE has \`${left[0].trim()}\`, which a shadow root cannot match`)
  if (/[`\\]|\$\{/.test(sheet)) throw new Error('PROOF_STYLE holds a backtick, backslash or `${`')
  return `${sheet}\n:host{display:block;container-type:inline-size}`
}

/** The generated module's text. @param {string} style */
export function buildModule(style) {
  return [
    '// Code generated by scripts/skills/review-page-style/build.mjs from PROOF_STYLE. DO NOT EDIT.',
    `// Regenerate with \`${UPDATE_COMMAND}\`.`,
    '',
    '/** The hosted review page stylesheet, for a shadow root whose host is the page. */',
    `export const REVIEW_PAGE_STYLE = \`${shadowStyle(style)}\``,
    '',
  ].join('\n')
}

/**
 * Regenerate, or compare against, the committed module.
 * @param {{check?: boolean, outPath?: string, style?: string}} [options]
 * @returns {{ok: boolean, message: string}}
 */
export function run({
  check = false,
  outPath = path.join(REPO_ROOT, OUTPUT_FILE),
  style = PROOF_STYLE,
} = {}) {
  const expected = buildModule(style)
  const out = path.relative(REPO_ROOT, outPath)
  if (!check) {
    fs.writeFileSync(outPath, expected)
    return { ok: true, message: `wrote ${out}` }
  }
  let current = null
  try {
    current = fs.readFileSync(outPath, 'utf8')
  } catch {
    // An absent module is stale.
  }
  return current === expected
    ? { ok: true, message: `${out} is up to date` }
    : {
        ok: false,
        message: `${out} is stale against PROOF_STYLE; regenerate with \`${UPDATE_COMMAND}\``,
      }
}

if (isMainModule(import.meta.url)) {
  const { values } = parseArgs({
    options: { check: { type: 'boolean', default: false }, out: { type: 'string' } },
    allowPositionals: false,
    strict: true,
  })
  const result = run({
    check: values.check,
    ...(values.out ? { outPath: path.resolve(values.out) } : {}),
  })
  if (result.ok) console.log(result.message)
  else {
    console.error(result.message)
    process.exitCode = 1
  }
}
