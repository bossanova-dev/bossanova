#!/usr/bin/env node

// Generator + gate: the docs site's vendored copy of @bossanova/web-helpers, and
// one implementation of every shared helper across the three browser trees.
//
// lib/web-helpers (`@bossanova/web-helpers`) is the single source for the
// browser helpers the web app, the marketing site and the docs site share. Web
// and marketing import it through the pnpm workspace. The docs site cannot: it
// is deliberately OUTSIDE the root workspace (services/docs/pnpm-workspace.yaml
// says why), and it is part of the public mirror while lib/web-helpers is
// stripped from it. So docs builds from a generated byte copy of the modules it
// imports, under services/docs/src/vendor/web-helpers/.
//
//   node scripts/sync-docs-web-helpers.mjs           write the vendored copy
//   node scripts/sync-docs-web-helpers.mjs --check   fail on any drift
//
// Each vendored file is GENERATED_HEADER(name) followed by the source bytes,
// unchanged. `--check` (wired into `make -C scripts lint`) exits 1 when:
//   - a vendored file is missing, or differs from what the generator writes by
//     even one byte (a hand edit, or a source edit nobody re-synced);
//   - the vendor directory holds a file the generator would not write;
//   - a top-level `function` / `const` / `let` / `class` named like one of the
//     package's exports is declared again under services/web/src,
//     services/marketing/src or services/docs/src (the vendor directory
//     excluded) — a second implementation of a shared helper.
// Writing is idempotent: a second run changes nothing.
//
// In the public mirror lib/web-helpers and the TS apps are stripped, and the
// vendored copy is the only one left; with neither present the check says so
// and passes. lib/web-helpers missing while services/web is present is a broken
// tree and fails.

//
// guard-id: web-helpers-single-source
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'

import { isMainModule } from '../skills-toolbox/main-module.mjs'

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

/** The package source every module is read from. */
export const SOURCE_DIR = 'lib/web-helpers/src'
/** Where docs' generated copy lives. The generator owns every file in it. */
export const VENDOR_DIR = 'services/docs/src/vendor/web-helpers'
/** The modules docs imports, and so the only ones vendored. */
export const VENDORED_MODULES = ['googleTag.ts', 'sentry-init.ts']
/** Trees that must not carry a second implementation of a shared helper. */
export const CONSUMER_ROOTS = ['services/web/src', 'services/marketing/src', 'services/docs/src']

const CONSUMER_EXTENSIONS = new Set(['.ts', '.tsx', '.mts', '.js', '.jsx', '.mjs', '.astro'])
const SKIP_DIRS = new Set(['node_modules', 'dist', 'build', 'gen', '.astro', '.docusaurus'])

/** The fixed header a vendored file starts with. */
export function generatedHeader(name) {
  return [
    `// GENERATED by scripts/sync-docs-web-helpers.mjs from ${SOURCE_DIR}/${name}. DO NOT EDIT.`,
    '// Edit the source and re-run the script; `--check` fails on any difference.',
    '',
    '',
  ].join('\n')
}

const DECLARATION =
  /^(?:export\s+)?(?:declare\s+)?(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm
const EXPORTED_DECLARATION =
  /^export\s+(?:declare\s+)?(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm

/** Names of the top-level `export function|const|let|class` declarations in a module. */
export function exportedNames(text) {
  return [...text.matchAll(EXPORTED_DECLARATION)].map((m) => m[1])
}

/** Top-level `function|const|let|class` declarations, exported or not, with 1-based lines. */
export function topLevelDeclarations(text) {
  const found = []
  for (const m of text.matchAll(DECLARATION)) {
    found.push({ name: m[1], line: text.slice(0, m.index).split('\n').length })
  }
  return found
}

const rel = (root, full) => path.relative(root, full).split(path.sep).join('/')

function walk(dir, acc) {
  let entries
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true })
  } catch (err) {
    if (err.code === 'ENOENT') return acc
    throw err
  }
  for (const entry of entries) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) walk(full, acc)
    } else {
      acc.push(full)
    }
  }
  return acc
}

/** The vendored files the generator writes: `{ name, content }` per module. */
export function expectedVendorFiles(root = REPO_ROOT) {
  return VENDORED_MODULES.map((name) => ({
    name,
    content: generatedHeader(name) + fs.readFileSync(path.join(root, SOURCE_DIR, name), 'utf8'),
  }))
}

/**
 * Every top-level declaration in a consumer tree named like a package export.
 * The vendor directory is skipped: it IS the package, byte for byte.
 */
export function findRedeclarations(root = REPO_ROOT) {
  const exported = new Map()
  for (const file of walk(path.join(root, SOURCE_DIR), [])) {
    if (path.extname(file) !== '.ts') continue
    for (const name of exportedNames(fs.readFileSync(file, 'utf8'))) {
      exported.set(name, rel(root, file))
    }
  }
  const vendor = path.join(root, VENDOR_DIR)
  const found = []
  let scanned = 0
  for (const consumer of CONSUMER_ROOTS) {
    for (const file of walk(path.join(root, consumer), [])) {
      if (file === vendor || file.startsWith(`${vendor}${path.sep}`)) continue
      if (!CONSUMER_EXTENSIONS.has(path.extname(file))) continue
      scanned++
      for (const { name, line } of topLevelDeclarations(fs.readFileSync(file, 'utf8'))) {
        if (exported.has(name)) {
          found.push({ file: rel(root, file), line, name, source: exported.get(name) })
        }
      }
    }
  }
  return { found, scanned, exports: exported.size }
}

/**
 * Write (`write: true`) or check the vendored copy, then check the consumer
 * trees for re-declared exports.
 *
 * @returns {{ ok: boolean, failures: string[], written: string[], skipped?: string,
 *   vendored: number, scanned: number, exports: number }}
 */
export function syncDocsWebHelpers({ root = REPO_ROOT, write = false } = {}) {
  const failures = []
  const written = []
  if (!fs.existsSync(path.join(root, SOURCE_DIR))) {
    if (!fs.existsSync(path.join(root, 'services/web'))) {
      return {
        ok: true,
        failures,
        written,
        skipped: `${SOURCE_DIR} and services/web are absent (public projection); the vendored copy is the only one`,
        vendored: 0,
        scanned: 0,
        exports: 0,
      }
    }
    failures.push(`${SOURCE_DIR}: missing, so the vendored docs copy has no source to match`)
    return { ok: false, failures, written, vendored: 0, scanned: 0, exports: 0 }
  }

  const vendorDir = path.join(root, VENDOR_DIR)
  let expected
  try {
    expected = expectedVendorFiles(root)
  } catch (err) {
    failures.push(
      `${SOURCE_DIR}: cannot read a vendored module's source (${err.code || err.message})`,
    )
    return { ok: false, failures, written, vendored: 0, scanned: 0, exports: 0 }
  }
  const expectedNames = new Set(expected.map((file) => file.name))

  if (write) fs.mkdirSync(vendorDir, { recursive: true })
  for (const { name, content } of expected) {
    const target = path.join(vendorDir, name)
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null
    if (current === content) continue
    if (write) {
      fs.writeFileSync(target, content)
      written.push(`${VENDOR_DIR}/${name}`)
    } else if (current === null) {
      failures.push(
        `${VENDOR_DIR}/${name}: missing; run \`node scripts/sync-docs-web-helpers.mjs\``,
      )
    } else {
      failures.push(
        `${VENDOR_DIR}/${name}: differs from ${SOURCE_DIR}/${name}; edit the source, never the copy, and run \`node scripts/sync-docs-web-helpers.mjs\``,
      )
    }
  }
  for (const full of walk(vendorDir, [])) {
    const name = rel(vendorDir, full)
    if (expectedNames.has(name)) continue
    if (write) {
      fs.rmSync(full)
      written.push(`${VENDOR_DIR}/${name} (removed)`)
    } else {
      failures.push(
        `${VENDOR_DIR}/${name}: not written by the generator; the vendor directory holds only ${VENDORED_MODULES.join(', ')}`,
      )
    }
  }

  const { found, scanned, exports } = findRedeclarations(root)
  for (const hit of found) {
    const from = hit.file.startsWith('services/docs/')
      ? `the vendored copy (${VENDOR_DIR})`
      : '@bossanova/web-helpers'
    failures.push(
      `${hit.file}:${hit.line}: declares ${hit.name}, which ${hit.source} exports; import it from ${from} instead of keeping a second implementation`,
    )
  }
  return {
    ok: failures.length === 0,
    failures,
    written,
    vendored: expected.length,
    scanned,
    exports,
  }
}

if (isMainModule(import.meta.url)) {
  const { values } = parseArgs({
    options: {
      check: { type: 'boolean', default: false },
      root: { type: 'string' },
    },
    allowPositionals: false,
    strict: true,
  })
  const result = syncDocsWebHelpers({ root: values.root ?? REPO_ROOT, write: !values.check })
  for (const file of result.written) console.log(`wrote ${file}`)
  if (!result.ok) {
    console.error('web-helpers sync check failed:')
    for (const failure of result.failures) console.error(`  ${failure}`)
    process.exit(1)
  }
  if (result.skipped) {
    console.log(`web-helpers sync skipped: ${result.skipped}`)
  } else {
    console.log(
      `web-helpers OK (${result.vendored} vendored docs file(s) fresh; 0 of ${result.exports} shared exports re-declared across ${result.scanned} files in ${CONSUMER_ROOTS.join(', ')})`,
    )
  }
}
