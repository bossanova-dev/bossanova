package main

import "time"

// Spec is the versioned, store-backed fixture input. Sessions may refer to
// existing repository IDs or keys in Repos. Worktrees are created by the caller.
type Spec struct {
	Version  int                `json:"version"`
	Repos    []RepoSpec         `json:"repos,omitempty"`
	Accounts []AgentAccountSpec `json:"accounts,omitempty"`
	Sessions []SessionSpec      `json:"sessions"`
}

// RepoSpec registers a fresh offline repository through the daemon store.
type RepoSpec struct {
	Key           string `json:"key"`
	DisplayName   string `json:"display_name"`
	LocalPath     string `json:"local_path"`
	OriginURL     string `json:"origin_url"`
	MergeStrategy string `json:"merge_strategy,omitempty"`
}

// SessionSpec describes persisted state unavailable through CreateSession.
// Attention is derived by bossd from state, blocked reasons and display fields;
// timeline events are persisted rotation decisions, rather than invented RPC output.
type SessionSpec struct {
	Key                 string              `json:"key"`
	RepoID              string              `json:"repo_id"`
	Title               string              `json:"title"`
	Plan                string              `json:"plan"`
	WorktreePath        string              `json:"worktree_path"`
	BranchName          string              `json:"branch_name"`
	BaseBranch          string              `json:"base_branch"`
	State               int                 `json:"state"`
	PRNumber            *int                `json:"pr_number,omitempty"`
	IsQuickChat         bool                `json:"is_quick_chat"`
	ArchivedAt          *time.Time          `json:"archived_at,omitempty"`
	DisplayLabel        string              `json:"display_label"`
	DisplayIntent       int32               `json:"display_intent"`
	HasDisplaySpinner   bool                `json:"has_display_spinner"`
	BlockedReason       string              `json:"blocked_reason"`
	RunBlockedReason    string              `json:"run_blocked_reason"`
	SetupError          string              `json:"setup_error"`
	IsAutomationEnabled bool                `json:"is_automation_enabled"`
	Chats               []ChatSpec          `json:"chats"`
	CheckSnapshots      []CheckSnapshotSpec `json:"check_snapshots"`
	Timeline            []TimelineSpec      `json:"timeline"`
}

// ChatSpec records a conversation, including failed or replaced history.
type ChatSpec struct {
	AgentSessionID    string  `json:"agent_session_id"`
	ProviderSessionID *string `json:"provider_session_id,omitempty"`
	Title             string  `json:"title"`
	Model             string  `json:"model"`
	Role              string  `json:"role"`
	StartError        string  `json:"start_error"`
	ReclaimReason     string  `json:"reclaim_reason"`
}

// CheckSnapshotSpec is one persisted PR-check observation.
type CheckSnapshotSpec struct {
	PolledAt       time.Time `json:"polled_at"`
	HeadSHA        string    `json:"head_sha"`
	RawJSON        string    `json:"raw_json"`
	ComputedStatus int       `json:"computed_status"`
}

// TimelineSpec is one rotation decision included in a session timeline.
type TimelineSpec struct {
	ID          string     `json:"id"`
	ChatID      string     `json:"chat_id"`
	Provider    string     `json:"provider"`
	Trigger     string     `json:"trigger"`
	FromAccount string     `json:"from_account"`
	ToAccount   string     `json:"to_account"`
	ResetAt     *time.Time `json:"reset_at,omitempty"`
	Outcome     string     `json:"outcome"`
	Detail      string     `json:"detail"`
	CreatedAt   time.Time  `json:"created_at"`
}

// Result maps fixture keys to IDs generated by bossd's stores.
type Result struct {
	SessionIDs map[string]string `json:"session_ids"`
	RepoIDs    map[string]string `json:"repo_ids,omitempty"`
}
