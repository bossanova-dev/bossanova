// The variables the gh wrapper reads. PATH puts the wrapper first; the label
// names who is spending the quota.
const (
	EnvReal  = "BOSS_GH_REAL"
	EnvDir   = "BOSS_GH_USAGE_DIR"
	EnvLabel = "BOSS_GH_USAGE_LABEL"
)

// EnvClaudeEnvFile names a script Claude Code sources before every Bash
// command. A login shell rebuilds PATH after spawn (macOS path_helper and
// brew shellenv put the real gh first), so Env points it at a script that
// puts the wrapper back in front.
const EnvClaudeEnvFile = "CLAUDE_ENV_FILE"

// Label prefixes for calls bossd does not make itself: a cron's gate and
// agent session record cron:<job name>, every other managed session
// session:<kind>.
const (
	LabelPrefixCron    = "cron:"
	LabelPrefixSession = "session:"
)

// shimDirName is the wrapper's directory inside the ledger directory. Read and
// Prune skip directories, so it can live beside the hour buckets.
const shimDirName = "bin"

// pathScriptName is the script EnvClaudeEnvFile names. It is not executable,
// so the wrapper dir on PATH adds no command besides gh.
const pathScriptName = "gh-path.sh"

// pathScript puts the wrapper dir first on PATH unless it already is.
const pathScript = `# Generated by bossd: puts the gh usage wrapper back first on PATH.
case "$PATH" in
@BIN@ | @BIN@:*) ;;
*) PATH=@BIN@${PATH:+:$PATH}; export PATH ;;
esac
`

// shimScript is the generated gh wrapper. It classifies the call with the
// rule quotaFor applies to the daemon's own calls (`gh api <path>` other than
// graphql spends core, every other networked command graphql), skips the
// commands that make no quota-spending call, and asks the trusted helper to
// route reads onto an installation token. It appends one ledger line, then
// execs the real gh with its arguments, stdin, stdout, stderr and exit status
// untouched. The record runs in a subshell with its errors discarded,
// so a ledger that cannot be written never stops the real call.
const shimScript = `#!/bin/sh
` + shimMarker + `
# routes eligible reads onto an installation token. Do not edit; rewritten on restart.
real=${` + EnvReal + `:-@REAL@}
dir=${` + EnvDir + `:-@DIR@}
helper=@BOSS@
quota=graphql
case "${1-}" in
api)
	case "${2-}" in
	graphql) ;;
	'' | rate_limit | /rate_limit) quota= ;;
	*) quota=core ;;
	esac
	;;
'' | --version | version | help | --help | -h | completion | config | alias | auth) quota= ;;
esac
identity=user
if [ -n "$quota" ] && [ -n "$helper" ] && [ -x "$helper" ]; then
	case "${1-}" in
	api | pr | run)
		cred=$("$helper" __gh-read-credential -- "$@" </dev/null 2>/dev/null) || cred=
		case "$cred" in
		*' '*)
			id=${cred%% *}
			tok=${cred#* }
			# Enumerate ASCII so locale collation cannot admit other characters.
			case "$id" in
			'' | *[!0123456789]*) ;;
			*)
				case "$tok" in
				'' | *[!ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_]*) ;;
				*)
					identity=installation:$id
					unset GITHUB_TOKEN GH_ENTERPRISE_TOKEN GITHUB_ENTERPRISE_TOKEN
					GH_TOKEN=$tok; export GH_TOKEN
					;;
				esac
				;;
			esac
			;;
		esac
		;;
	esac
fi
if [ -n "$quota" ]; then
	(
		umask 077
		stamp=$(date -u '+%s %Y%m%d%H') || exit 0
		printf '{"at":%s,"label":"%s","quota":"%s","identity":"%s"}\n' "${stamp% *}" "${` + EnvLabel + `-}" "$quota" "$identity" >>"$dir/${stamp#* }` + bucketExt + `"
	) 2>/dev/null
fi
exec "$real" "$@"
`

// shimMarker is the wrapper's second line. lookGH skips any gh that carries it,
// so a daemon started from another daemon's metered session never takes that
// wrapper for the real gh, which would make it exec itself forever.
const shimMarker = "# Generated by bossd at start: meters gh calls into the GitHub usage ledger,"

// Shim is an installed gh wrapper. A nil *Shim is a wrapper that could not be
// installed: its Env is empty, so gh behaves exactly as it did unmetered.
type Shim struct {
	binDir    string
	real      string
	ledgerDir string
	basePath  string
}

type shimOptions struct {
	readCredentialHelper string
}

// ShimOption configures the generated gh wrapper.
type ShimOption func(*shimOptions)

// WithReadCredentialHelper embeds a trusted boss executable in the wrapper.
// Only absolute paths to executable regular files are accepted. Callers must
// resolve the trusted binary themselves; the wrapper has no environment override.
func WithReadCredentialHelper(bossBin string) ShimOption {
	return func(opts *shimOptions) {
		if !filepath.IsAbs(bossBin) {
			return
		}
		info, err := os.Stat(bossBin)
		if err == nil && info.Mode().IsRegular() && info.Mode()&0o111 != 0 {
			opts.readCredentialHelper = bossBin
		}
	}
}

// InstallShim writes the gh wrapper to <ledgerDir>/bin/gh, replacing any
// previous one atomically. pathEnv is the PATH the real gh is resolved on and
// the PATH Env puts the wrapper in front of. When no gh resolves it removes a
// stale wrapper and returns nil: metering degrades, gh behaviour does not.
func InstallShim(ledgerDir, pathEnv string, opts ...ShimOption) (*Shim, error) {
	binDir := filepath.Join(ledgerDir, shimDirName)
	shimPath := filepath.Join(binDir, "gh")
	basePath := withoutDir(pathEnv, binDir)
	real := lookGH(basePath)
	if real == "" {
		if err := os.Remove(shimPath); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return nil, fmt.Errorf("remove stale gh wrapper: %w", err)
		}
		return nil, nil
	}
	if err := os.MkdirAll(binDir, 0o700); err != nil {
		return nil, fmt.Errorf("create gh wrapper dir: %w", err)
	}
	var options shimOptions
	for _, opt := range opts {
		opt(&options)
	}
	script := strings.NewReplacer("@REAL@", shellQuote(real), "@DIR@", shellQuote(ledgerDir), "@BOSS@", shellQuote(options.readCredentialHelper)).Replace(shimScript)
	if err := writeFileAtomic(shimPath, script, 0o700); err != nil {
		return nil, fmt.Errorf("write gh wrapper: %w", err)
	}
	pathFix := strings.ReplaceAll(pathScript, "@BIN@", shellQuote(binDir))
	if err := writeFileAtomic(filepath.Join(binDir, pathScriptName), pathFix, 0o600); err != nil {
		return nil, fmt.Errorf("write gh wrapper PATH script: %w", err)
	}
	return &Shim{binDir: binDir, real: real, ledgerDir: ledgerDir, basePath: basePath}, nil
}

// Env returns the variables that route a process's gh calls through the
// wrapper under label, or nil for a nil Shim. The label is sanitised to the
// characters a JSON string needs no escaping for. It replaces any inherited
// CLAUDE_ENV_FILE so a Claude Code chat keeps the wrapper first.
func (s *Shim) Env(label string) map[string]string {
	if s == nil {
		return nil
	}
	path := s.binDir
	if s.basePath != "" {
		path += string(os.PathListSeparator) + s.basePath
	}
	return map[string]string{
		"PATH":           path,
		EnvReal:          s.real,
		EnvDir:           s.ledgerDir,
		EnvLabel:         SanitizeLabel(label),
		EnvClaudeEnvFile: filepath.Join(s.binDir, pathScriptName),
	}
}

// SanitizeLabel lowercases label and replaces every byte outside
// [a-z0-9:._-] with '-', so the wrapper can write it into a JSON line
// verbatim. It caps the result at the ledger's label length.
func SanitizeLabel(label string) string {
	out := []byte(strings.ToLower(label))
	for i, c := range out {
		switch {
		case c >= 'a' && c <= 'z', c >= '0' && c <= '9', c == ':', c == '.', c == '_', c == '-':
		default:
			out[i] = '-'
		}
	}
	if len(out) > maxLabelBytes {
		out = out[:maxLabelBytes]
	}
	return string(out)
}

// lookGH finds an executable gh on pathEnv, skipping empty and relative
// entries the way exec.LookPath refuses them, and any bossd gh wrapper.
func lookGH(pathEnv string) string {
	for _, dir := range filepath.SplitList(pathEnv) {
		if !filepath.IsAbs(dir) {
			continue
		}
		candidate := filepath.Join(dir, "gh")
		info, err := os.Stat(candidate)
		if err == nil && info.Mode().IsRegular() && info.Mode()&0o111 != 0 && !isShim(candidate) {
			return candidate
		}
	}
	return ""
}

// isShim reports whether the file at path is a bossd gh wrapper. A file it
// cannot read is not one: the real gh is only ever read, never trusted, here.
func isShim(path string) bool {
	f, err := os.Open(path) // #nosec G304 -- path is a gh candidate on the daemon's own PATH
	if err != nil {
		return false
	}
	defer func() { _ = f.Close() }()
	head := make([]byte, 256)
	n, _ := io.ReadFull(f, head)
	return bytes.Contains(head[:n], []byte(shimMarker))
}

// withoutDir drops every entry of pathEnv that names dir, so a daemon started
// from a metered shell never resolves the wrapper as the real gh.
func withoutDir(pathEnv, dir string) string {
	entries := filepath.SplitList(pathEnv)
	kept := entries[:0]
	for _, entry := range entries {
		if entry != "" && filepath.Clean(entry) == dir {
			continue
		}
		kept = append(kept, entry)
	}
	return strings.Join(kept, string(os.PathListSeparator))
}

func writeFileAtomic(path, content string, mode os.FileMode) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".gh-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer func() { _ = os.Remove(tmpName) }()
	_, werr := tmp.WriteString(content)
	cherr := tmp.Chmod(mode)
	cerr := tmp.Close()
	if err := errors.Join(werr, cherr, cerr); err != nil {
		return err
	}
	return os.Rename(tmpName, path)
}

func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
