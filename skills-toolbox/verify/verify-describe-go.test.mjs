test('overflow retains route counts, exports and tests with valid bounded blocks', (t) => {
  const repo = gitFixture(t)
  repo.write({ 'go.mod': 'module example/api\n' })
  const base = repo.commit()
  repo.write({
    'router.go': `package api\nimport "net/http"\nfunc Added() {}\nfunc setup() {\n${Array.from({ length: 25 }, (_, i) => `mux.Handle("GET /${i}/${'x'.repeat(180)}", serve)`).join('\n')}\n}`,
    'router_test.go': 'package api\nfunc TestMany(t *T) {}',
  })
  const head = repo.commit()
  const result = boundDescription(
    'boss-verify-go',
    describeGo(envelopeFor(repo.dir, base, head, 'other'), { cwd: repo.dir }),
  )
  assert.equal(result.blocks.length, 16)
  assert.match(result.items[0], /25 added.*9 not shown as blocks/)
  assert.match(result.items.join(' '), /Added/)
  assert.match(result.items.join(' '), /TestMany/)
  assert.deepEqual(refineDescription(result), [])
})
