test('Go exported declarations include methods, grouped types and multi-name variables', () => {
  const parsed = exportedIdentifiers(`package api
// func Fake() {}
const (A = 1; B = 2)
var C, D = 1, 2
type (
 E struct { Field string }
 F interface { Public() }
)
func (r *E) Serve() {}
func (r private) Public() {}
func New() { var Local int }
`)
  assert.equal(parsed.package, 'api')
  assert.deepEqual([...parsed.names].sort(), ['A', 'B', 'C', 'D', 'E', 'E.Serve', 'F', 'New'])
  assert.deepEqual(
    testFunctions('package api\nfunc TestOne(t *T) {}\nfunc BenchmarkTwo(b *B) {}'),
    ['TestOne', 'BenchmarkTwo'],
  )
  assert.deepEqual(testFunctions('package api\ntype TestSuite struct{}\nvar TestValue int'), [])
  assert.equal(isGeneratedGo('// Code generated by tool. DO NOT EDIT.\npackage api'), true)
  assert.equal(isGeneratedGo('package api\n// Code generated by tool. DO NOT EDIT.'), false)
})

test('function types and callback signatures do not invent exported methods', () => {
  const parsed = exportedIdentifiers(`package api
type Fn func(Ctx) Error
func Use(mw func(Handler) Handler) {}
func New() func(Ctx) Error { return nil }
func Multi(
 mw func(Handler) Handler,
) {}
func (s *Server) Serve() {}
`)
  assert.deepEqual([...parsed.names].sort(), ['Fn', 'Multi', 'New', 'Server.Serve', 'Use'])
})

test('cross-package file moves report each package export change but no route move', (t) => {
  const repo = gitFixture(t)
  repo.write({
    'go.mod': 'module example/api\n',
    'a/server.go':
      'package api\nimport "net/http"\nfunc Exported() {}\nfunc setup() { mux.Handle("GET /x", serve) }',
  })
  const base = repo.commit()
  repo.move('a/server.go', 'b/server.go')
  const head = repo.commit()
  const result = describeGo(envelopeFor(repo.dir, base, head, 'housekeeping'), { cwd: repo.dir })
  assert.equal(result.blocks, undefined)
  assert.match(result.items.join(' '), /example\/api\/a: exported removed Exported/)
  assert.match(result.items.join(' '), /example\/api\/b: exported added Exported/)
})

