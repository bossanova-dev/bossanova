test('package set differences ignore moves, generated code and package main; nearest module names facts', (t) => {
  const repo = gitFixture(t)
  repo.write({
    'go.mod': 'module example/root\n',
    'nested/go.mod': 'module example/inner\n',
    'nested/a.go': 'package api\nfunc Move() {}\nfunc Gone() {}',
    'nested/b.go': 'package api\n',
    'main.go': 'package main\nfunc Before() {}',
  })
  const base = repo.commit()
  repo.write({
    'nested/a.go': 'package api\nfunc Added() {}',
    'nested/b.go': 'package api\nfunc Move() {}',
    'main.go': 'package main\nfunc After() {}',
    'generated.go': '// Code generated by tool. DO NOT EDIT.\npackage api\nfunc Noise() {}',
  })
  const head = repo.commit()
  const facts = describeGo(envelopeFor(repo.dir, base, head, 'other'), { cwd: repo.dir })
  assert.equal(facts.breaking, false)
  assert.equal(facts.items.length, 1)
  assert.match(facts.items[0], /example\/inner.*Added.*Gone/)
  assert.doesNotMatch(facts.items.join(' '), /Move|Noise|Before|After/)
})

for (const framework of ['chi', 'http'])
  test(`${framework} route and tests land beside changed code, including payload wrapper`, async (t) => {
    const repo = gitFixture(t)
    repo.write({ 'go.mod': 'module example/api\n', 'router.go': 'package api\n' })
    const base = repo.commit()
    const registration =
      framework === 'chi' ? 'r.Post("/v1/claims", Create)' : 'mux.Handle("POST /v1/claims", Create)'
    const imp = framework === 'chi' ? 'github.com/go-chi/chi/v5' : 'net/http'
    repo.write({
      'router.go': `package api\nimport "${imp}"\nfunc Create() {}\nfunc setup() { ${registration} }`,
      'router_test.go':
        framework === 'chi'
          ? 'package api\nfunc TestCreate(t *T) {}'
          : 'package api\nvar _ = It("creates", func() {})',
    })
    const head = repo.commit()
    const envelope = envelopeFor(repo.dir, base, head, 'other', 'boss-verify-go')
    const result = describeGo(envelope, { cwd: repo.dir })
    assert.equal(result.blocks[0].path, '/v1/claims')
    assert.equal(result.blocks[0].method, 'POST')
    assert.match(result.items.join(' '), /router_test.go/)
    if (framework === 'chi') assert.match(result.items.join(' '), /TestCreate/)
    assert.deepEqual(
      describeGo(envelopeFor(repo.dir, base, head, 'housekeeping'), { cwd: repo.dir }).items,
      [],
    )
    const builtinDir = new URL(
      '../../lib/bossalib/contract/plugin/skillpayload/skills/boss-verify/extensions/',
      import.meta.url,
    ).pathname
    const found = discoverExtensions({
      core: 'boss-verify',
      role: 'proof-describe',
      builtinDir,
      root: repo.dir,
    })
    const extension = found.extensions.find((e) => e.name === 'boss-verify-go')
    assert.equal(extension.builtin, true)
    assert.ok(extension.describeAreas.includes('no-sign-off'))
    const wrapper = new URL(
      '../../lib/bossalib/contract/plugin/skillpayload/skills/boss-verify/extensions/boss-verify-go/describe.mjs',
      import.meta.url,
    ).href
    assert.equal(runDescriberScript(wrapper, envelope, repo.dir).blocks[0].path, '/v1/claims')
    assert.equal(
      runDescriberScript(
        new URL('./verify-describe-go.mjs', import.meta.url).href,
        envelope,
        repo.dir,
      ).blocks[0].method,
      'POST',
    )
  })

