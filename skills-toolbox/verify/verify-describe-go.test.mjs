test('independent modules keep identical route registrations distinct', (t) => {
  const repo = gitFixture(t)
  const router =
    'package api\nimport "net/http"\nfunc setup() { mux.Handle("GET /healthz", serve) }'
  repo.write({
    'a/go.mod': 'module example/a\n',
    'b/go.mod': 'module example/b\n',
    'a/router.go': router,
    'b/router.go': router,
  })
  const base = repo.commit()
  repo.write({ 'a/router.go': 'package api\n', 'b/router.go': `${router}\n// changed` })
  const head = repo.commit()
  const result = describeGo(envelopeFor(repo.dir, base, head, 'other'), { cwd: repo.dir })
  assert.deepEqual(
    result.blocks.map((r) => [r.path, r.change]),
    [['/healthz', 'removed']],
  )
})

