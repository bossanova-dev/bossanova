package main

import (
	"reflect"
	"strings"
	"testing"
)

func TestScanSourceDeclarations(t *testing.T) {
	source := `// Code generated by fixture. DO NOT EDIT.
package example
const Public = 1
const private = 2
var First, Second, hidden int
type Exported struct{}
type privateType int
func PublicFunc() {}
func privateFunc() {}
func (Exported) Method() {}
type Wide interface {
 Read()
 Write()
 Close() error
 Exported
 other.Embedded
}
type narrow interface { hidden() }
`
	got, err := scanSource("pkg/source.go", []byte(source))
	if err != nil {
		t.Fatal(err)
	}
	if got.File != "pkg/source.go" || got.Dir != "pkg" || got.Pkg != "example" || !got.Generated || got.Test || got.Lines != strings.Count(source, "\n") || got.Exported != 6 {
		t.Fatalf("unexpected file metrics: %+v", got)
	}
	want := []interfaceMetrics{{Name: "Wide", Exported: true, Methods: 3, Embeds: 2}, {Name: "narrow", Methods: 1}}
	if !reflect.DeepEqual(got.Interfaces, want) {
		t.Fatalf("interfaces = %#v, want %#v", got.Interfaces, want)
	}
	if got.Tests == nil || len(got.Tests) != 0 {
		t.Fatalf("tests = %#v", got.Tests)
	}
}

func TestScanSourceTests(t *testing.T) {
	source := "package example\n" + `func TestCases(t *testing.T) {
 t.Run("plain", func(t *testing.T) { t.Run("nested", func(t *testing.T) {}) })
 t.Run(` + "`raw`" + `, func(t *testing.T) {})
 t.Run(variable, func(t *testing.T) {})
 other.Run("unrelated", nil)
}
func helper(t *testing.T) { t.Run("helper", nil) }
func (thing) TestMethod(t *testing.T) {}
func TestWithoutBody(t *testing.T)
`
	got, err := scanSource("source_test.go", []byte(source))
	if err != nil {
		t.Fatal(err)
	}
	want := []testMetrics{{Name: "TestCases", Subtests: []string{"plain", "nested", "raw"}}, {Name: "TestWithoutBody", Subtests: []string{}}}
	if !got.Test || got.Generated || got.Dir != "." || !reflect.DeepEqual(got.Tests, want) {
		t.Fatalf("test metrics = %#v", got)
	}
}

func TestScanSourceInvalid(t *testing.T) {
	if _, err := scanSource("invalid.go", []byte("not Go source")); err == nil {
		t.Fatal("expected parse error")
	}
}

func TestScanSourceCountsNewlines(t *testing.T) {
	got, err := scanSource("empty.go", []byte("package empty"))
	if err != nil {
		t.Fatal(err)
	}
	if got.Lines != 0 || got.Exported != 0 || got.Interfaces == nil || got.Tests == nil {
		t.Fatalf("empty metrics = %+v", got)
	}
}
